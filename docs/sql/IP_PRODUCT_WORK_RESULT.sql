-- 설비별 작업 실적관리 실 구현 — 신규 테이블 3종
-- 1) IP_PRODUCT_WORK_RESULT      : 실적 헤더 (작업지시 RUN_NO × 일련번호 SEQ_NO 복수 실적)
-- 2) IP_PRODUCT_WORK_RESULT_BAD  : 불량 detail (실적별 × WQC 부적합코드)
-- 3) IP_EQUIP_DOWNTIME_RESULT    : 설비비가동 실적 (작업지시 연계, 시작/종료)

CREATE TABLE IP_PRODUCT_WORK_RESULT (
  RUN_NO            VARCHAR2(30)  NOT NULL,
  SEQ_NO            VARCHAR2(2)   NOT NULL,
  ORGANIZATION_ID   NUMBER        NOT NULL,
  MACHINE_CODE      VARCHAR2(30),
  WORKSTAGE_CODE    VARCHAR2(10),
  RESULT_QTY        NUMBER        DEFAULT 0,
  WORK_TIME         NUMBER        DEFAULT 0,
  WORKER_COUNT      NUMBER        DEFAULT 0,
  WORKER_NAME       VARCHAR2(100),
  RESULT_STATUS     VARCHAR2(10)  DEFAULT 'WIP',
  ENTER_BY          VARCHAR2(20),
  ENTER_DATE        DATE,
  LAST_MODIFY_BY    VARCHAR2(20),
  LAST_MODIFY_DATE  DATE,
  CONSTRAINT PK_IP_PRODUCT_WORK_RESULT PRIMARY KEY (RUN_NO, SEQ_NO, ORGANIZATION_ID)
)
/

CREATE TABLE IP_PRODUCT_WORK_RESULT_BAD (
  RUN_NO            VARCHAR2(30)  NOT NULL,
  SEQ_NO            VARCHAR2(2)   NOT NULL,
  BAD_CODE          VARCHAR2(20)  NOT NULL,
  ORGANIZATION_ID   NUMBER        NOT NULL,
  BAD_QTY           NUMBER        DEFAULT 0,
  REMARK            VARCHAR2(500),
  ENTER_BY          VARCHAR2(20),
  ENTER_DATE        DATE,
  CONSTRAINT PK_IP_PRODUCT_WORK_RESULT_BAD PRIMARY KEY (RUN_NO, SEQ_NO, BAD_CODE, ORGANIZATION_ID)
)
/

CREATE TABLE IP_EQUIP_DOWNTIME_RESULT (
  RUN_NO            VARCHAR2(30)  NOT NULL,
  DT_SEQ            NUMBER        NOT NULL,
  ORGANIZATION_ID   NUMBER        NOT NULL,
  MACHINE_CODE      VARCHAR2(30),
  WORKSTAGE_CODE    VARCHAR2(10),
  REASON_CODE       VARCHAR2(20),
  START_TIME        DATE,
  END_TIME          DATE,
  MEMO              VARCHAR2(500),
  WORKER            VARCHAR2(100),
  ENTER_BY          VARCHAR2(20),
  ENTER_DATE        DATE,
  LAST_MODIFY_BY    VARCHAR2(20),
  LAST_MODIFY_DATE  DATE,
  CONSTRAINT PK_IP_EQUIP_DOWNTIME_RESULT PRIMARY KEY (RUN_NO, DT_SEQ, ORGANIZATION_ID)
)
/

COMMENT ON TABLE IP_PRODUCT_WORK_RESULT IS '설비별 작업 실적 헤더 (작업지시별 복수 실적)'
/
COMMENT ON COLUMN IP_PRODUCT_WORK_RESULT.SEQ_NO IS '실적 일련번호 (2자리 01~99)'
/
COMMENT ON COLUMN IP_PRODUCT_WORK_RESULT.RESULT_STATUS IS '처리구분: WIP=진행, DONE=완료(수정불가)'
/
COMMENT ON COLUMN IP_PRODUCT_WORK_RESULT.MACHINE_CODE IS '설비코드 (IMCN_MACHINE.MACHINE_CODE)'
/
COMMENT ON COLUMN IP_PRODUCT_WORK_RESULT.WORKSTAGE_CODE IS '공정코드 (IP_PRODUCT_WORKSTAGE.WORKSTAGE_CODE)'
/
COMMENT ON TABLE IP_PRODUCT_WORK_RESULT_BAD IS '작업 실적 불량 detail (WQC BAD REASON CODE)'
/
COMMENT ON COLUMN IP_PRODUCT_WORK_RESULT_BAD.BAD_CODE IS '부적합코드 (ISYS_CODE_MASTER WQC BAD REASON CODE)'
/
COMMENT ON TABLE IP_EQUIP_DOWNTIME_RESULT IS '설비비가동 실적 (시작/종료, 종료 NULL=진행중)'
/
COMMENT ON COLUMN IP_EQUIP_DOWNTIME_RESULT.REASON_CODE IS '비가동 사유코드 (IP_EQUIP_DOWNTIME_REASON.REASON_CODE)'
/
