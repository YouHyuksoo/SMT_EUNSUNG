DECLARE
  -- 품목별 라우팅(RT-<품번>) 17건을 공정 순서가 같은 것끼리 묶어 코드 기준 라우팅으로 옮긴다.
  -- 1회성 이관. IP_ROUTING_GROUPS.ITEM_CODE 가 있고 값이 남아 있을 때만 동작한다(재실행해도 변화 없음).
  v_old   NUMBER;
  v_no    NUMBER := 0;
  v_code  VARCHAR2(50);
  v_name  VARCHAR2(200);
BEGIN
  SELECT COUNT(*) INTO v_old FROM IP_ROUTING_GROUPS WHERE ITEM_CODE IS NOT NULL;
  IF v_old = 0 THEN
    RETURN;
  END IF;

  FOR sig IN (
    SELECT sg, COUNT(*) item_cnt, MIN(rc) rep_rc
      FROM (
        SELECT g.ROUTING_CODE rc,
               (SELECT LISTAGG(p.PROCESS_SEQ || ':' || p.WORKSTAGE_CODE, '>')
                       WITHIN GROUP (ORDER BY p.PROCESS_SEQ)
                  FROM IP_ROUTING_PROCESSES p
                 WHERE p.ORGANIZATION_ID = g.ORGANIZATION_ID AND p.ROUTING_CODE = g.ROUTING_CODE) sg
          FROM IP_ROUTING_GROUPS g
         WHERE g.ORGANIZATION_ID = 1 AND g.ITEM_CODE IS NOT NULL
      )
     GROUP BY sg
     ORDER BY COUNT(*) DESC, sg
  ) LOOP
    v_no := v_no + 1;
    v_code := 'RT-' || LPAD(v_no, 2, '0');

    SELECT LISTAGG(w.WORKSTAGE_NAME, ' → ') WITHIN GROUP (ORDER BY p.PROCESS_SEQ)
      INTO v_name
      FROM IP_ROUTING_PROCESSES p
      JOIN IP_PRODUCT_WORKSTAGE w
        ON w.WORKSTAGE_CODE = p.WORKSTAGE_CODE AND w.ORGANIZATION_ID = p.ORGANIZATION_ID
     WHERE p.ORGANIZATION_ID = 1 AND p.ROUTING_CODE = sig.rep_rc;

    INSERT INTO IP_ROUTING_GROUPS (ORGANIZATION_ID, ROUTING_CODE, ITEM_CODE, ROUTING_NAME, USE_YN, CREATED_BY)
    VALUES (1, v_code, NULL, v_name, 'Y', 'SYSTEM');

    INSERT INTO IP_ROUTING_PROCESSES
      (ORGANIZATION_ID, ROUTING_CODE, PROCESS_SEQ, WORKSTAGE_CODE, EXECUTION_TYPE, JOB_ORDER_YN,
       SUBCON_SUPPLIER_CODE, STANDARD_TIME, SETUP_TIME, USE_YN, CREATED_BY)
    SELECT p.ORGANIZATION_ID, v_code, p.PROCESS_SEQ, p.WORKSTAGE_CODE, p.EXECUTION_TYPE, p.JOB_ORDER_YN,
           p.SUBCON_SUPPLIER_CODE, p.STANDARD_TIME, p.SETUP_TIME, p.USE_YN, 'SYSTEM'
      FROM IP_ROUTING_PROCESSES p
     WHERE p.ORGANIZATION_ID = 1 AND p.ROUTING_CODE = sig.rep_rc;

    -- 같은 서명을 가진 모든 옛 그룹의 품목이 새 라우팅 코드를 문다.
    UPDATE ID_ITEM i
       SET i.ROUTING_CODE = v_code
     WHERE i.ORGANIZATION_ID = 1
       AND i.ITEM_CODE IN (
         SELECT g.ITEM_CODE
           FROM IP_ROUTING_GROUPS g
          WHERE g.ORGANIZATION_ID = 1 AND g.ITEM_CODE IS NOT NULL
            AND (SELECT LISTAGG(p.PROCESS_SEQ || ':' || p.WORKSTAGE_CODE, '>')
                        WITHIN GROUP (ORDER BY p.PROCESS_SEQ)
                   FROM IP_ROUTING_PROCESSES p
                  WHERE p.ORGANIZATION_ID = g.ORGANIZATION_ID AND p.ROUTING_CODE = g.ROUTING_CODE) = sig.sg
       );
  END LOOP;

  -- 옛 품목별 라우팅 삭제(자식 → 부모). 투입자재는 0건이었다.
  DELETE FROM IP_ROUTING_PROCESSES
   WHERE ORGANIZATION_ID = 1
     AND ROUTING_CODE IN (SELECT ROUTING_CODE FROM IP_ROUTING_GROUPS WHERE ITEM_CODE IS NOT NULL);
  DELETE FROM IP_ROUTING_GROUPS WHERE ITEM_CODE IS NOT NULL;
  COMMIT;
END;
/
