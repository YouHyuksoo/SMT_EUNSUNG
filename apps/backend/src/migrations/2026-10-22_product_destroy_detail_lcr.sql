--   BAD_REASON_CODE = 불량유형(DESTROY BAD TYPE SMT/ASSY), SHIFT_CODE = 주(A)/야(B),
--   BAD_CAUSE_BY = 원인(M 작업=HUMAN, S 원자재, E 설비 — E 를 이번에 추가), CHARGER = 작업자(수기)
-- 새 칸은 팀·제품구분·불량구분1·발생공정·검출공정·폐기단가·폐기금액만 더한다.
