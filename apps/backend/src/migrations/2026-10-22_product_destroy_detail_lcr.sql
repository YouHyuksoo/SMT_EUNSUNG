/
COMMENT ON COLUMN IP_PRODUCT_WORK_QC.DESTROY_PRODUCT_TYPE IS '공정폐기 제품구분 (DESTROY PRODUCT TYPE)'
/
COMMENT ON COLUMN IP_PRODUCT_WORK_QC.DESTROY_BAD_CATEGORY IS '공정폐기 불량구분1 (DESTROY BAD CATEGORY, 생산2팀)'
/
COMMENT ON COLUMN IP_PRODUCT_WORK_QC.OCCUR_PROCESS_CODE IS '공정폐기 발생공정 (DESTROY PROCESS ASSY, 생산2팀)'
/
COMMENT ON COLUMN IP_PRODUCT_WORK_QC.DETECT_PROCESS_CODE IS '공정폐기 검출공정 (DESTROY PROCESS SMT / ASSY)'
/
COMMENT ON COLUMN IP_PRODUCT_WORK_QC.DESTROY_UNIT_PRICE IS '공정폐기 단가 (등록 시점 스냅샷: 구매단가, 없으면 BOM 자재원가)'
/
COMMENT ON COLUMN IP_PRODUCT_WORK_QC.DESTROY_AMOUNT IS '공정폐기 금액 = BAD_QTY x DESTROY_UNIT_PRICE (등록 시점)'
/

CREATE SEQUENCE SEQ_IP_LCR_DESTROY START WITH 1 INCREMENT BY 1 NOCACHE
/

CREATE TABLE IP_LCR_DESTROY (
  LCR_SEQ           NUMBER        NOT NULL,
  ORGANIZATION_ID   NUMBER        NOT NULL,
  MEASURE_DATE      DATE          NOT NULL,
  ITEM_CODE         VARCHAR2(30)  NOT NULL,
  ITEM_NAME         VARCHAR2(200),
  MODEL_NAME        VARCHAR2(100),
  CUSTOMER_CODE     VARCHAR2(20),
  ARRAY_QTY         NUMBER        NOT NULL,
  MOUNT_QTY         NUMBER        NOT NULL,
  UNIT_PRICE_SUM    NUMBER        NOT NULL,
  USE_QTY           NUMBER        NOT NULL,
  DESTROY_AMOUNT    NUMBER        NOT NULL,
  MEASURER          VARCHAR2(50),
  COMMENTS          VARCHAR2(500),
  ENTER_BY          VARCHAR2(20),
  ENTER_DATE        DATE,
  LAST_MODIFY_BY    VARCHAR2(20),
  LAST_MODIFY_DATE  DATE,
  CONSTRAINT PK_IP_LCR_DESTROY PRIMARY KEY (LCR_SEQ),
  CONSTRAINT CK_IP_LCR_DESTROY_ARRAY CHECK (ARRAY_QTY > 0)
)
/
CREATE INDEX IX_IP_LCR_DESTROY_DATE ON IP_LCR_DESTROY (ORGANIZATION_ID, MEASURE_DATE)
/
COMMENT ON TABLE IP_LCR_DESTROY IS 'LCR 측정 자재 폐기 (생산1팀). 등록 시점 BOM·단가를 스냅샷으로 남긴다'
/
COMMENT ON COLUMN IP_LCR_DESTROY.MEASURE_DATE IS '측정일자'
/
COMMENT ON COLUMN IP_LCR_DESTROY.ITEM_CODE IS '품번 (BOM 에 L/C/R 위치가 직접 달린 면 품목: TOP/BOT)'
/
COMMENT ON COLUMN IP_LCR_DESTROY.ARRAY_QTY IS 'LCR 진행 수량 (연배 수)'
/
COMMENT ON COLUMN IP_LCR_DESTROY.MOUNT_QTY IS '1연배 L/C/R 실장 수량 합'
/
COMMENT ON COLUMN IP_LCR_DESTROY.UNIT_PRICE_SUM IS 'L/C/R 실장 자재 단가 합'
/
COMMENT ON COLUMN IP_LCR_DESTROY.USE_QTY IS '실 사용 수량 = MOUNT_QTY x ARRAY_QTY'
/
COMMENT ON COLUMN IP_LCR_DESTROY.DESTROY_AMOUNT IS '폐기금액 = SUM(자재 실장수량 x 단가) x ARRAY_QTY'
/
COMMENT ON COLUMN IP_LCR_DESTROY.MEASURER IS '측정자 (수기)'
/

CREATE TABLE IP_LCR_DESTROY_DETAIL (
  LCR_SEQ          NUMBER        NOT NULL,
  CHILD_ITEM_CODE  VARCHAR2(30)  NOT NULL,
  ORGANIZATION_ID  NUMBER        NOT NULL,
  LOCATION_INFO    VARCHAR2(2500),
  MOUNT_QTY        NUMBER        NOT NULL,
  UNIT_PRICE       NUMBER,
  USE_QTY          NUMBER        NOT NULL,
  DESTROY_AMOUNT   NUMBER        NOT NULL,
  CONSTRAINT PK_IP_LCR_DESTROY_DETAIL PRIMARY KEY (LCR_SEQ, CHILD_ITEM_CODE),
  CONSTRAINT FK_IP_LCR_DESTROY_DETAIL FOREIGN KEY (LCR_SEQ) REFERENCES IP_LCR_DESTROY (LCR_SEQ) ON DELETE CASCADE
)
/
COMMENT ON TABLE IP_LCR_DESTROY_DETAIL IS 'LCR 폐기 자재 내역 (등록 시점 BOM L/C/R 자재 스냅샷)'
/

