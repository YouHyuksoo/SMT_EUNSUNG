BEGIN
  EXECUTE IMMEDIATE q'[COMMENT ON TABLE IM_ITEM_WORKSTAGE_INV_WS IS '공정별 공정재고 (품목·공정). 공정입고·출고 트리거가 유지한다. 품목 합계는 IM_ITEM_WORKSTAGE_INVENTORY 와 같다']';
  EXECUTE IMMEDIATE q'[COMMENT ON TABLE IM_ITEM_WS_MOVE IS '공정간 이동 — 후공정에서 매거진을 스캔하면 반제품을 출발 공정에서 도착 공정으로 옮긴다 (라벨·도착 공정당 한 번)']';
END;
/
CREATE OR REPLACE TRIGGER TRG_IM_WS_RECEIPT_INV_WS
  /* 공정별 공정재고: 공정입고 + (수정은 차이, 공정을 바꾸면 옮긴다). 2026-10-18 */
  AFTER INSERT OR UPDATE OF RECEIPT_QTY, WORKSTAGE_CODE ON IM_ITEM_WORKSTAGE_RECEIPT
  FOR EACH ROW
BEGIN
  IF UPDATING THEN
    UPDATE IM_ITEM_WORKSTAGE_INV_WS SET INVENTORY_QTY = INVENTORY_QTY - NVL(:OLD.RECEIPT_QTY, 0), LAST_MODIFY_DATE = SYSDATE
     WHERE ITEM_CODE = :OLD.ITEM_CODE AND ORGANIZATION_ID = :OLD.ORGANIZATION_ID AND WORKSTAGE_CODE = :OLD.WORKSTAGE_CODE;
  END IF;
  MERGE INTO IM_ITEM_WORKSTAGE_INV_WS t
  USING (SELECT :NEW.ITEM_CODE c, :NEW.ORGANIZATION_ID o, :NEW.WORKSTAGE_CODE w FROM DUAL) s
     ON (t.ITEM_CODE = s.c AND t.ORGANIZATION_ID = s.o AND t.WORKSTAGE_CODE = s.w)
   WHEN MATCHED THEN UPDATE SET t.INVENTORY_QTY = t.INVENTORY_QTY + NVL(:NEW.RECEIPT_QTY, 0), t.LAST_MODIFY_DATE = SYSDATE, t.LAST_MODIFY_BY = SUBSTR(:NEW.ENTER_BY, 1, 20)
   WHEN NOT MATCHED THEN INSERT (ITEM_CODE, ORGANIZATION_ID, WORKSTAGE_CODE, INVENTORY_QTY, LAST_MODIFY_DATE, LAST_MODIFY_BY)
                         VALUES (s.c, s.o, s.w, NVL(:NEW.RECEIPT_QTY, 0), SYSDATE, SUBSTR(:NEW.ENTER_BY, 1, 20));
END;
/
CREATE OR REPLACE TRIGGER TRG_IM_WS_ISSUE_INV_WS
  /* 공정별 공정재고: 공정출고 − (수정은 차이, 공정을 바꾸면 옮긴다). 2026-10-18 */
  AFTER INSERT OR UPDATE OF ISSUE_QTY, WORKSTAGE_CODE ON IM_ITEM_WORKSTAGE_ISSUE
  FOR EACH ROW
BEGIN
  IF UPDATING THEN
    UPDATE IM_ITEM_WORKSTAGE_INV_WS SET INVENTORY_QTY = INVENTORY_QTY + NVL(:OLD.ISSUE_QTY, 0), LAST_MODIFY_DATE = SYSDATE
     WHERE ITEM_CODE = :OLD.ITEM_CODE AND ORGANIZATION_ID = :OLD.ORGANIZATION_ID AND WORKSTAGE_CODE = :OLD.WORKSTAGE_CODE;
  END IF;
  MERGE INTO IM_ITEM_WORKSTAGE_INV_WS t
  USING (SELECT :NEW.ITEM_CODE c, :NEW.ORGANIZATION_ID o, :NEW.WORKSTAGE_CODE w FROM DUAL) s
     ON (t.ITEM_CODE = s.c AND t.ORGANIZATION_ID = s.o AND t.WORKSTAGE_CODE = s.w)
   WHEN MATCHED THEN UPDATE SET t.INVENTORY_QTY = t.INVENTORY_QTY - NVL(:NEW.ISSUE_QTY, 0), t.LAST_MODIFY_DATE = SYSDATE, t.LAST_MODIFY_BY = SUBSTR(:NEW.ENTER_BY, 1, 20)
   WHEN NOT MATCHED THEN INSERT (ITEM_CODE, ORGANIZATION_ID, WORKSTAGE_CODE, INVENTORY_QTY, LAST_MODIFY_DATE, LAST_MODIFY_BY)
                         VALUES (s.c, s.o, s.w, -NVL(:NEW.ISSUE_QTY, 0), SYSDATE, SUBSTR(:NEW.ENTER_BY, 1, 20));
END;
/
-- 시작값: 지금 품목 현재고 전부를 공정 미지정('*')으로 (트리거를 만든 뒤 차이만 맞춘다 — 그 사이 들어온 입출고도 맞는다)
MERGE INTO IM_ITEM_WORKSTAGE_INV_WS t
USING (SELECT i.ITEM_CODE, i.ORGANIZATION_ID,
              NVL(i.INVENTORY_QTY, 0) - NVL((SELECT SUM(w.INVENTORY_QTY) FROM IM_ITEM_WORKSTAGE_INV_WS w
                                              WHERE w.ITEM_CODE = i.ITEM_CODE AND w.ORGANIZATION_ID = i.ORGANIZATION_ID), 0) AS DIFF
         FROM IM_ITEM_WORKSTAGE_INVENTORY i) s
   ON (t.ITEM_CODE = s.ITEM_CODE AND t.ORGANIZATION_ID = s.ORGANIZATION_ID AND t.WORKSTAGE_CODE = '*')
 WHEN MATCHED THEN UPDATE SET t.INVENTORY_QTY = t.INVENTORY_QTY + s.DIFF, t.LAST_MODIFY_DATE = SYSDATE, t.LAST_MODIFY_BY = 'INIT'
 WHEN NOT MATCHED THEN INSERT (ITEM_CODE, ORGANIZATION_ID, WORKSTAGE_CODE, INVENTORY_QTY, LAST_MODIFY_DATE, LAST_MODIFY_BY)
                       VALUES (s.ITEM_CODE, s.ORGANIZATION_ID, '*', s.DIFF, SYSDATE, 'INIT')
/
COMMIT
/
CREATE OR REPLACE TRIGGER TRG_IM_WS_RECEIPT_INFAC
  /* 인팩 전송용 공정재고: 공정입고(자재 출고 등) + . 조립실적 반제품 입고(AOI_RT·ASSY_MANUAL·ASSY_ADJ)와
     공정간 이동 입고(WS_MOVE)는 넣지 않는다. 2026-10-17 / 2026-10-18 */
  AFTER INSERT OR UPDATE OF RECEIPT_QTY ON IM_ITEM_WORKSTAGE_RECEIPT
  FOR EACH ROW
  WHEN (NVL(NEW.ENTER_BY, '*') NOT IN ('AOI_RT', 'ASSY_MANUAL', 'ASSY_ADJ', 'WS_MOVE'))
DECLARE
  v_qty NUMBER := NVL(:NEW.RECEIPT_QTY, 0) - NVL(:OLD.RECEIPT_QTY, 0);
  v_cnt NUMBER;
BEGIN
  IF v_qty = 0 THEN RETURN; END IF;
  SELECT COUNT(*) INTO v_cnt FROM ID_ITEM WHERE ITEM_CODE = :NEW.ITEM_CODE AND SUPPLIER_CODE = 'IP' AND ROWNUM = 1;
  IF v_cnt = 0 THEN RETURN; END IF;
  MERGE INTO IM_ITEM_WS_INV_INFAC t
  USING (SELECT :NEW.ITEM_CODE c, :NEW.ORGANIZATION_ID o FROM DUAL) s
     ON (t.ITEM_CODE = s.c AND t.ORGANIZATION_ID = s.o)
   WHEN MATCHED THEN UPDATE SET t.INVENTORY_QTY = NVL(t.INVENTORY_QTY, 0) + v_qty, t.LAST_MODIFY_DATE = SYSDATE, t.LAST_MODIFY_BY = 'WS RECEIPT'
   WHEN NOT MATCHED THEN INSERT (ITEM_CODE, ORGANIZATION_ID, INVENTORY_QTY, LAST_MODIFY_DATE, LAST_MODIFY_BY)
                         VALUES (s.c, s.o, v_qty, SYSDATE, 'WS RECEIPT');
END;
