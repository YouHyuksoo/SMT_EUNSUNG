-- 사용자 지시: "매거진을 후공정에서 스캔할때 해당공정으로 이동이 되는 처리를 통해 공정간 이동이 되어야함"
--
-- 1. 공정입고·출고에 공정(WORKSTAGE_CODE) 칼럼을 붙인다. 기본 '*' (공정 미지정 — 기존 행·자재 공정입고·제품 입고 차감).
-- 2. 공정별 현재고 IM_ITEM_WORKSTAGE_INV_WS (품목·공정). 기존 품목 현재고 IM_ITEM_WORKSTAGE_INVENTORY 는 그대로 둔다
--    — DB 함수 9개가 품목 한 행으로 읽는다(F_GET_MAT_WS_* 등). 공정 이동은 품목 합계로 0 이라 기존 현재고·마감 잔량은 변하지 않는다.
-- 3. 이동 기록 IM_ITEM_WS_MOVE (매거진 라벨·도착 공정당 한 번).
-- 4. 인팩 전송용 공정재고는 이동 입고(ENTER_BY = 'WS_MOVE')를 넣지 않는다.
-- 5. 매거진 라벨 번호 인덱스 (후공정 스캔이 라벨로 런카드 IO 를 찾는다).
-- 프로시저·트리거 (oracle_db_scripts): F_GET_ASSY_SEMI_ITEM, P_ASSY_RESULT_ADD, P_WIP_MOVE_BY_MAGAZINE,
--   P_WIP_MOVE_FROM_WS_IO, TRG_IP_PRODUCT_WS_IO_WIP_MOVE
-- 원복: 이 파일 끝 주석
-- =====================================================================
ALTER TABLE IM_ITEM_WORKSTAGE_RECEIPT ADD (WORKSTAGE_CODE VARCHAR2(20) DEFAULT '*' NOT NULL)
/
ALTER TABLE IM_ITEM_WORKSTAGE_ISSUE ADD (WORKSTAGE_CODE VARCHAR2(20) DEFAULT '*' NOT NULL)
/
BEGIN
  EXECUTE IMMEDIATE q'[COMMENT ON COLUMN IM_ITEM_WORKSTAGE_RECEIPT.WORKSTAGE_CODE IS '공정 (W180 SMT 반제품 · 후공정 이동 도착 공정, * = 공정 미지정)']';
  EXECUTE IMMEDIATE q'[COMMENT ON COLUMN IM_ITEM_WORKSTAGE_ISSUE.WORKSTAGE_CODE IS '공정 (W180 SMT 원자재 소비 · 후공정 이동 출발 공정, * = 공정 미지정)']';
END;
/
CREATE TABLE IM_ITEM_WORKSTAGE_INV_WS (
  ITEM_CODE        VARCHAR2(20)  NOT NULL,
  ORGANIZATION_ID  NUMBER        NOT NULL,
  WORKSTAGE_CODE   VARCHAR2(20)  NOT NULL,
  INVENTORY_QTY    NUMBER        DEFAULT 0 NOT NULL,
  LAST_MODIFY_DATE DATE,
  LAST_MODIFY_BY   VARCHAR2(20),
  CONSTRAINT PK_IM_ITEM_WORKSTAGE_INV_WS PRIMARY KEY (ITEM_CODE, ORGANIZATION_ID, WORKSTAGE_CODE)
)
/
CREATE TABLE IM_ITEM_WS_MOVE (
  MAGAZINE_LABEL_NO   VARCHAR2(30)  NOT NULL,
  TO_WORKSTAGE_CODE   VARCHAR2(20)  NOT NULL,
  ORGANIZATION_ID     NUMBER        NOT NULL,
  FROM_WORKSTAGE_CODE VARCHAR2(20)  NOT NULL,
  ITEM_CODE           VARCHAR2(20)  NOT NULL,
  MOVE_QTY            NUMBER        NOT NULL,
  MOVE_DATE           DATE          NOT NULL,
  RUN_NO              VARCHAR2(30),
  LINE_CODE           VARCHAR2(20),
  IO_DATE             DATE,
  IO_SEQUENCE         NUMBER,
  ENTER_DATE          DATE          DEFAULT SYSDATE,
  ENTER_BY            VARCHAR2(20),
  CONSTRAINT PK_IM_ITEM_WS_MOVE PRIMARY KEY (MAGAZINE_LABEL_NO, TO_WORKSTAGE_CODE, ORGANIZATION_ID)
)
/
CREATE INDEX IX_IM_ITEM_WS_MOVE_1 ON IM_ITEM_WS_MOVE (MOVE_DATE)
/
CREATE INDEX IX_IP_RUN_CARD_IO_MAG_LABEL ON IP_PRODUCT_RUN_CARD_IO (MAGAZINE_LABEL_NO)
