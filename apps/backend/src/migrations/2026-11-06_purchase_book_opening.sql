DECLARE
  n NUMBER;
  PROCEDURE ensure_col(p_col VARCHAR2, p_def VARCHAR2) IS
    c NUMBER;
  BEGIN
    SELECT COUNT(*) INTO c FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'IM_PURCHASE_BOOK_OPENING' AND COLUMN_NAME = p_col;
    IF c = 0 THEN
      EXECUTE IMMEDIATE 'ALTER TABLE IM_PURCHASE_BOOK_OPENING ADD (' || p_def || ')';
    END IF;
  END;
BEGIN
  -- 구매팀 일보 장부 기초재고. 기준일(BASE_DATE) 0시 시점의 품목별 원자재 장부 수량
  -- (창고 + 외주 + 재공 + 제품 속 원자재). 화면은 기준일부터 입고·제품출고×BOM 을 더하고 빼서 이어 쌓는다.
  SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME = 'IM_PURCHASE_BOOK_OPENING';
  IF n = 0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE IM_PURCHASE_BOOK_OPENING (
      ORGANIZATION_ID NUMBER NOT NULL,
      BASE_DATE       DATE NOT NULL,
      ITEM_CODE       VARCHAR2(20) NOT NULL,
      OPENING_QTY     NUMBER DEFAULT 0 NOT NULL,
      CONSTRAINT PK_IM_PURCHASE_BOOK_OPENING PRIMARY KEY (ORGANIZATION_ID, BASE_DATE, ITEM_CODE)
    )';
  END IF;
  ensure_col('BOOK_GROUP', 'BOOK_GROUP VARCHAR2(100)');
  ensure_col('ITEM_CLASS', 'ITEM_CLASS VARCHAR2(20)');
  ensure_col('UNIT_PRICE', 'UNIT_PRICE NUMBER');
  ensure_col('ENTER_BY', 'ENTER_BY VARCHAR2(30)');
  ensure_col('ENTER_DATE', 'ENTER_DATE DATE DEFAULT SYSDATE');
  EXECUTE IMMEDIATE q'[COMMENT ON TABLE IM_PURCHASE_BOOK_OPENING IS '구매팀 일보 장부 기초재고 (기준일 0시, 원자재 품목별)']';
  EXECUTE IMMEDIATE q'[COMMENT ON COLUMN IM_PURCHASE_BOOK_OPENING.BOOK_GROUP IS '보고서 거래처 묶음 (예: 인팩, 인팩이피엠, 티에스모스트)']';
  EXECUTE IMMEDIATE q'[COMMENT ON COLUMN IM_PURCHASE_BOOK_OPENING.ITEM_CLASS IS '원자재 구분: OEM, A/S, 불용']';
  EXECUTE IMMEDIATE q'[COMMENT ON COLUMN IM_PURCHASE_BOOK_OPENING.UNIT_PRICE IS '기초 등록 당시 단가 (참고용, 금액 계산은 단가마스터)']';
END;
/
