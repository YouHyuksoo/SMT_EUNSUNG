DECLARE
  -- =====================================================================
  -- 2026-10-27 공정폐기 원장(IP_PRODUCT_DESTROY) 신설 — ESDBext 적용
  --
  -- 사용자 지시: "WORK_QC 는 수리판정일 뿐이고 폐기이력은 따로 재고처럼 모아야 하는건데"
  -- 폐기 한 건 = 한 행. 상태(DESTROY_STATUS)로 재고처럼 관리한다.
  --   D 폐기보관(폐기 재고) / R 반품(재고에서 나감) / C 취소(잘못 등록 — 행은 남긴다)
  -- 사용처: apps/backend/src/modules/quality/services/product-destroy.service.ts
  --
  -- 1. 시퀀스·테이블·인덱스 — 없을 때만 만든다
  -- 2. 공통코드 DESTROY STATUS — 없을 때만 넣는다
  -- 3. IP_PRODUCT_WORK_QC 의 옛 폐기(검사처리 D) 행을 옮긴다 — SOURCE_* 키로 한 번만.
  --    원래 행은 수리판정 기록이라 그대로 둔다. 다시 실행하면 그 사이 쌓인 D 행만 더 옮긴다.
  -- =====================================================================
  n NUMBER;
  PROCEDURE ddl(p_sql VARCHAR2) IS BEGIN EXECUTE IMMEDIATE p_sql; END;
BEGIN
  SELECT COUNT(*) INTO n FROM USER_SEQUENCES WHERE SEQUENCE_NAME = 'SEQ_IP_PRODUCT_DESTROY';
  IF n = 0 THEN
    ddl('CREATE SEQUENCE SEQ_IP_PRODUCT_DESTROY START WITH 1 INCREMENT BY 1 NOCACHE');
  END IF;

  SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME = 'IP_PRODUCT_DESTROY';
  IF n = 0 THEN
    ddl(q'~CREATE TABLE IP_PRODUCT_DESTROY (
      DESTROY_SEQ           NUMBER         NOT NULL,
      ORGANIZATION_ID       NUMBER         NOT NULL,
      DESTROY_DATE          DATE           NOT NULL,
      DESTROY_STATUS        VARCHAR2(1)    DEFAULT 'D' NOT NULL,
      SERIAL_NO             VARCHAR2(30),
      ITEM_CODE             VARCHAR2(30)   NOT NULL,
      MODEL_NAME            VARCHAR2(100),
      MODEL_SUFFIX          VARCHAR2(50),
      DESTROY_QTY           NUMBER         NOT NULL,
      LINE_CODE             VARCHAR2(10),
      WORKSTAGE_CODE        VARCHAR2(10),
      DESTROY_TEAM          VARCHAR2(10),
      BAD_REASON_CODE       VARCHAR2(10),
      DESTROY_PRODUCT_TYPE  VARCHAR2(10),
      DESTROY_BAD_CATEGORY  VARCHAR2(10),
      OCCUR_PROCESS_CODE    VARCHAR2(10),
      DETECT_PROCESS_CODE   VARCHAR2(10),
      BAD_CAUSE_BY          VARCHAR2(1),
      SHIFT_CODE            VARCHAR2(1),
      DEPARTMENT_CODE       VARCHAR2(20),
      WORKER_NAME           VARCHAR2(20),
      UNIT_PRICE            NUMBER,
      DESTROY_AMOUNT        NUMBER,
      RETURN_DATE           DATE,
      RETURN_BY             VARCHAR2(20),
      CANCEL_DATE           DATE,
      CANCEL_BY             VARCHAR2(20),
      CANCEL_REASON         VARCHAR2(500),
      COMMENTS              VARCHAR2(1000),
      SOURCE_SERIAL_NO      VARCHAR2(30),
      SOURCE_QC_SEQUENCE    NUMBER,
      ENTER_BY              VARCHAR2(20),
      ENTER_DATE            DATE,
      LAST_MODIFY_BY        VARCHAR2(20),
      LAST_MODIFY_DATE      DATE,
      CONSTRAINT PK_IP_PRODUCT_DESTROY PRIMARY KEY (DESTROY_SEQ),
      CONSTRAINT CK_IP_PRODUCT_DESTROY_STATUS CHECK (DESTROY_STATUS IN ('D', 'R', 'C')),
      CONSTRAINT CK_IP_PRODUCT_DESTROY_QTY CHECK (DESTROY_QTY > 0)
    )~');
  END IF;

  SELECT COUNT(*) INTO n FROM USER_INDEXES WHERE INDEX_NAME = 'IX_IP_PRODUCT_DESTROY_DATE';
  IF n = 0 THEN
    ddl('CREATE INDEX IX_IP_PRODUCT_DESTROY_DATE ON IP_PRODUCT_DESTROY (ORGANIZATION_ID, DESTROY_DATE)');
  END IF;
  SELECT COUNT(*) INTO n FROM USER_INDEXES WHERE INDEX_NAME = 'IX_IP_PRODUCT_DESTROY_SERIAL';
  IF n = 0 THEN
    ddl('CREATE INDEX IX_IP_PRODUCT_DESTROY_SERIAL ON IP_PRODUCT_DESTROY (SERIAL_NO, ORGANIZATION_ID)');
  END IF;
  SELECT COUNT(*) INTO n FROM USER_INDEXES WHERE INDEX_NAME = 'IX_IP_PRODUCT_DESTROY_SOURCE';
  IF n = 0 THEN
    ddl('CREATE INDEX IX_IP_PRODUCT_DESTROY_SOURCE ON IP_PRODUCT_DESTROY (SOURCE_SERIAL_NO, SOURCE_QC_SEQUENCE, ORGANIZATION_ID)');
  END IF;

  ddl(q'~COMMENT ON TABLE IP_PRODUCT_DESTROY IS '공정폐기 원장. 폐기 1건 = 1행, 상태(D 폐기보관 / R 반품 / C 취소)로 재고처럼 관리한다'~');
  ddl(q'~COMMENT ON COLUMN IP_PRODUCT_DESTROY.DESTROY_STATUS IS '상태 (DESTROY STATUS: D=폐기보관, R=반품, C=취소)'~');
  ddl(q'~COMMENT ON COLUMN IP_PRODUCT_DESTROY.SERIAL_NO IS '제품 시리얼. 바코드 미각인 제품(품번 + 수량 등록)은 비어 있다'~');
  ddl(q'~COMMENT ON COLUMN IP_PRODUCT_DESTROY.DESTROY_QTY IS '폐기 수량 (시리얼 등록은 1)'~');
  ddl(q'~COMMENT ON COLUMN IP_PRODUCT_DESTROY.DESTROY_TEAM IS '팀 (DESTROY TEAM: 1=생산1팀 SMT, 2=생산2팀 조립)'~');
  ddl(q'~COMMENT ON COLUMN IP_PRODUCT_DESTROY.BAD_REASON_CODE IS '불량유형 (DESTROY BAD TYPE SMT / ASSY, 옛 행은 WQC BAD REASON CODE)'~');
  ddl(q'~COMMENT ON COLUMN IP_PRODUCT_DESTROY.WORKER_NAME IS '작업자 (수기)'~');
  ddl(q'~COMMENT ON COLUMN IP_PRODUCT_DESTROY.UNIT_PRICE IS '단가 (등록 시점 스냅샷: 구매단가, 없으면 BOM 자재원가)'~');
  ddl(q'~COMMENT ON COLUMN IP_PRODUCT_DESTROY.DESTROY_AMOUNT IS '폐기금액 = DESTROY_QTY x UNIT_PRICE (등록 시점)'~');
  ddl(q'~COMMENT ON COLUMN IP_PRODUCT_DESTROY.CANCEL_REASON IS '취소 사유 — 잘못 등록한 폐기를 취소할 때'~');
  ddl(q'~COMMENT ON COLUMN IP_PRODUCT_DESTROY.SOURCE_QC_SEQUENCE IS 'IP_PRODUCT_WORK_QC 에서 옮긴 옛 폐기 행의 QC_SEQUENCE (이관 원본 키)'~');
END;
/

MERGE INTO ISYS_BASECODE t
USING (
  SELECT 'DESTROY STATUS' AS CODE_TYPE, 'C' AS CODE_NAME, '취소' AS K FROM DUAL
  UNION ALL SELECT 'DESTROY STATUS', 'D', '폐기보관' FROM DUAL
  UNION ALL SELECT 'DESTROY STATUS', 'R', '반품' FROM DUAL
) s
ON (t.CODE_TYPE = s.CODE_TYPE AND t.CODE_NAME = s.CODE_NAME AND t.ORGANIZATION_ID = 1)
WHEN NOT MATCHED THEN
  INSERT (CODE_TYPE, CODE_NAME, ORGANIZATION_ID, CODE_MEAN_KOR, CODE_MEAN_ENG, CODE_MEAN_LOCAL, CODE_GROUP,
          ENTER_DATE, ENTER_BY, LAST_MODIFY_DATE, LAST_MODIFY_BY)
  VALUES (s.CODE_TYPE, s.CODE_NAME, 1, s.K, s.K, s.K, 'SYSTEM', SYSDATE, 'ADMIN', SYSDATE, 'ADMIN');
/

INSERT INTO IP_PRODUCT_DESTROY (
  DESTROY_SEQ, ORGANIZATION_ID, DESTROY_DATE, DESTROY_STATUS,
  SERIAL_NO, ITEM_CODE, MODEL_NAME, MODEL_SUFFIX, DESTROY_QTY,
  LINE_CODE, WORKSTAGE_CODE,
  DESTROY_TEAM, BAD_REASON_CODE, DESTROY_PRODUCT_TYPE, DESTROY_BAD_CATEGORY,
  OCCUR_PROCESS_CODE, DETECT_PROCESS_CODE, BAD_CAUSE_BY, SHIFT_CODE, DEPARTMENT_CODE, WORKER_NAME,
  UNIT_PRICE, DESTROY_AMOUNT, RETURN_DATE, RETURN_BY, COMMENTS,
  SOURCE_SERIAL_NO, SOURCE_QC_SEQUENCE,
  ENTER_BY, ENTER_DATE, LAST_MODIFY_BY, LAST_MODIFY_DATE
)
SELECT SEQ_IP_PRODUCT_DESTROY.NEXTVAL, q.ORGANIZATION_ID, NVL(q.QC_DATE, NVL(q.ENTER_DATE, SYSDATE)),
       CASE WHEN q.RECEIPT_DEFICIT = '2' THEN 'R' ELSE 'D' END,
       CASE WHEN q.SERIAL_NO LIKE 'NOSN-%' THEN NULL ELSE q.SERIAL_NO END,
       NVL(q.ITEM_CODE, '*'), q.MODEL_NAME, q.MODEL_SUFFIX, GREATEST(NVL(q.BAD_QTY, 1), 1),
       q.LINE_CODE, q.WORKSTAGE_CODE,
       q.DESTROY_TEAM, q.BAD_REASON_CODE, q.DESTROY_PRODUCT_TYPE, q.DESTROY_BAD_CATEGORY,
       q.OCCUR_PROCESS_CODE, q.DETECT_PROCESS_CODE, q.BAD_CAUSE_BY, q.SHIFT_CODE, q.DEPARTMENT_CODE, q.CHARGER,
       q.DESTROY_UNIT_PRICE, q.DESTROY_AMOUNT,
       CASE WHEN q.RECEIPT_DEFICIT = '2' THEN q.REPAIR_DATE END,
       CASE WHEN q.RECEIPT_DEFICIT = '2' THEN q.LAST_MODIFY_BY END,
       q.COMMENTS,
       q.SERIAL_NO, q.QC_SEQUENCE,
       q.ENTER_BY, q.ENTER_DATE, 'MIGRATION', SYSDATE
  FROM IP_PRODUCT_WORK_QC q
 WHERE q.QC_INSPECT_HANDLING = 'D'
   AND NOT EXISTS (SELECT 1 FROM IP_PRODUCT_DESTROY d
                    WHERE d.SOURCE_SERIAL_NO = q.SERIAL_NO
                      AND d.SOURCE_QC_SEQUENCE = q.QC_SEQUENCE
                      AND d.ORGANIZATION_ID = q.ORGANIZATION_ID)
/
COMMIT
