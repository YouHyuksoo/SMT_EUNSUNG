-- AI_CHAT_FEEDBACKS 생성 (AI 채팅 응답 좋아요/싫어요)
--
-- 배경:
--   AI 모듈(ai/ai-knowledge)을 HANES 운영 방식으로 복구하면서, AI 채팅 패널의 좋아요/싫어요
--   (POST /ai/chat/feedback, DELETE /ai/chat/feedback/:id) 가 저장할 테이블이 이 DB 에 없다.
--   엔티티: apps/backend/src/entities/ai-chat-feedback.entity.ts
--
-- HANES 2026-07-01_ai_chat_feedbacks.sql 기준. 테넌트 키만 은성 기준으로 바꿨다:
--   HANES COMPANY/PLANT_CD → 은성 ORGANIZATION_ID(NUMBER)
-- FEEDBACK_ID 는 Oracle 12c IDENTITY 로 채번한다 (TypeORM PrimaryGeneratedColumn).

CREATE TABLE AI_CHAT_FEEDBACKS (
  FEEDBACK_ID      NUMBER          GENERATED BY DEFAULT AS IDENTITY,
  ORGANIZATION_ID  NUMBER          NOT NULL,
  ROUTE            VARCHAR2(200),
  MENU_CODE        VARCHAR2(50),
  QUESTION         CLOB            NOT NULL,
  ANSWER           CLOB            NOT NULL,
  SOURCES_JSON     CLOB,
  RATING           VARCHAR2(10)    NOT NULL,
  CREATED_BY       VARCHAR2(50)    NOT NULL,
  CREATED_AT       TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_AI_CHAT_FEEDBACKS PRIMARY KEY (FEEDBACK_ID),
  CONSTRAINT CK_AI_CHAT_FEEDBACKS_RATING CHECK (RATING IN ('LIKE','DISLIKE'))
)
/

CREATE INDEX IDX_AI_CHAT_FEEDBACKS_ORG     ON AI_CHAT_FEEDBACKS (ORGANIZATION_ID)
/

CREATE INDEX IDX_AI_CHAT_FEEDBACKS_MENU    ON AI_CHAT_FEEDBACKS (MENU_CODE)
/

CREATE INDEX IDX_AI_CHAT_FEEDBACKS_CREATED ON AI_CHAT_FEEDBACKS (CREATED_AT DESC)
/

COMMENT ON TABLE AI_CHAT_FEEDBACKS IS 'AI 채팅 응답 좋아요/싫어요 피드백 (질문·답변·출처 스냅샷)'
/
