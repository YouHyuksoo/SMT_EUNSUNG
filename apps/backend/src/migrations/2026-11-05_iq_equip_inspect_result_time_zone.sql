   WHERE TABLE_NAME = 'IQ_EQUIP_INSPECT_RESULT' AND COLUMN_NAME = 'TIME_ZONE';
  IF v_cnt = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE IQ_EQUIP_INSPECT_RESULT ADD (TIME_ZONE VARCHAR2(2))';
  END IF;

  EXECUTE IMMEDIATE q'[COMMENT ON COLUMN IQ_EQUIP_INSPECT_RESULT.TIME_ZONE IS '타임구간 A~J (작업시간 관리 WORKTIME 구간)']';
