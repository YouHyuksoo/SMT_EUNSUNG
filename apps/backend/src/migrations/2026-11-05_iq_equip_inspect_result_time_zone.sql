  -- 2026-11-05 설비별 검사실적(IQ_EQUIP_INSPECT_RESULT)에 타임구간 컬럼 추가 (멱등)
  --   TIME_ZONE 타임구간 A~J (작업시간 관리 ICOM_WORKTIME_RANGES 의 WORK_TYPE)
  --   기존 행과 설비별 검사실적관리(/oee/equip-inspect-result) 화면 저장분은 타임구간을 알 수 없어 NULL 로 둔다.
  v_table NUMBER;
  v_cnt   NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_table FROM USER_TABLES WHERE TABLE_NAME = 'IQ_EQUIP_INSPECT_RESULT';
