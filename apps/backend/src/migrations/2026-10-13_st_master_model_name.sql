-- 1단계 -----------------------------------------------------------------
ALTER TABLE IP_PRODUCT_ST_MASTER ADD (MODEL_NAME VARCHAR2(100));
/
ALTER TABLE IP_PRODUCT_ST_MASTER DROP CONSTRAINT PK_IP_PRODUCT_ST_MASTER DROP INDEX;
/
INSERT INTO IP_PRODUCT_ST_MASTER
       (ITEM_CODE, MACHINE_CODE, DATESET, ORGANIZATION_ID, DATEEND, ST_VALUE, CT_VALUE, NT_VALUE, TT_VALUE,
        REMARK, ENTER_BY, ENTER_DATE, LAST_MODIFY_BY, LAST_MODIFY_DATE, MODEL_NAME)
SELECT s.ITEM_CODE, s.MACHINE_CODE, s.DATESET, s.ORGANIZATION_ID, s.DATEEND, s.ST_VALUE, s.CT_VALUE, s.NT_VALUE, s.TT_VALUE,
       s.REMARK, s.ENTER_BY, s.ENTER_DATE, s.LAST_MODIFY_BY, s.LAST_MODIFY_DATE, mp.MODEL_NAME
  FROM IP_PRODUCT_ST_MASTER s
  JOIN (SELECT DISTINCT i.ITEM_CODE, i.ORGANIZATION_ID, m.MODEL_NAME
          FROM (SELECT DISTINCT ITEM_CODE, ORGANIZATION_ID FROM IP_PRODUCT_ST_MASTER) i
          JOIN IP_PRODUCT_MODEL_MASTER m
            ON m.ORGANIZATION_ID = i.ORGANIZATION_ID
           AND (m.ITEM_CODE = i.ITEM_CODE OR m.PART_NO = i.ITEM_CODE)) mp
    ON mp.ITEM_CODE = s.ITEM_CODE AND mp.ORGANIZATION_ID = s.ORGANIZATION_ID
 WHERE s.MODEL_NAME IS NULL;
/
DELETE FROM IP_PRODUCT_ST_MASTER WHERE MODEL_NAME IS NULL;
/
COMMIT;
/
ALTER TABLE IP_PRODUCT_ST_MASTER MODIFY (MODEL_NAME NOT NULL);
/
ALTER TABLE IP_PRODUCT_ST_MASTER MODIFY (ITEM_CODE NULL);
/
ALTER TABLE IP_PRODUCT_ST_MASTER ADD CONSTRAINT PK_IP_PRODUCT_ST_MASTER
  PRIMARY KEY (MODEL_NAME, MACHINE_CODE, DATESET, ORGANIZATION_ID);
/
COMMENT ON COLUMN IP_PRODUCT_ST_MASTER.MODEL_NAME IS '모델명 (IP_PRODUCT_MODEL_MASTER.MODEL_NAME). 반제품·제품 표준시간의 키';
/
COMMENT ON COLUMN IP_PRODUCT_ST_MASTER.ITEM_CODE IS '(폐기 예정) 2026-10-13 MODEL_NAME 키로 전환. 새 코드 배포 후 삭제한다';
/

