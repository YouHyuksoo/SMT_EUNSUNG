--                                        대상: ID_ITEM.SUPPLIER_CODE = 'IP' (ESEF 전송 대상과 같다)
--   TRG_IM_WS_RECEIPT_INFAC / TRG_IM_WS_ISSUE_INFAC  위 테이블을 움직이는 트리거
--   AOI 실시간 행은 시간대·품목별 한 행 (ENTER_BY = 'AOI_RT') — 함수 기반 유일 인덱스로 중복 행을 막는다.
-- 프로시저 (oracle_db_scripts): P_ASSY_RESULT_ADD_PID, P_WIP_ISSUE_CREATE, P_JOB_INFAC_DATA_CREATE
