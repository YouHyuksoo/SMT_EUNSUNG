CREATE TABLE IM_ITEM_WS_INV_INFAC (
  ITEM_CODE         VARCHAR2(30) NOT NULL,
  ORGANIZATION_ID   NUMBER       NOT NULL,
  INVENTORY_QTY     NUMBER       DEFAULT 0,
  LAST_MODIFY_DATE  DATE,
  LAST_MODIFY_BY    VARCHAR2(20),
  CONSTRAINT PK_IM_ITEM_WS_INV_INFAC PRIMARY KEY (ITEM_CODE, ORGANIZATION_ID)
)
/
BEGIN
  EXECUTE IMMEDIATE q'[COMMENT ON TABLE IM_ITEM_WS_INV_INFAC IS '인팩 전송(ESEF)용 원자재 공정재고 — 2026-10-17 전환 전 계산 방식 유지 (자재출고 +, 실사조정 −, 제품입고×BOM말단 −)']';
END;
/
-- 시작값: 지금 공정재고 장부의 인팩 자재 수량 (2026-10-17 강제 조정에서 제외한 값 그대로)
INSERT INTO IM_ITEM_WS_INV_INFAC (ITEM_CODE, ORGANIZATION_ID, INVENTORY_QTY, LAST_MODIFY_DATE, LAST_MODIFY_BY)
SELECT w.ITEM_CODE, w.ORGANIZATION_ID, SUM(NVL(w.INVENTORY_QTY, 0)), SYSDATE, 'INIT'
  FROM IM_ITEM_WORKSTAGE_INVENTORY w
 WHERE w.ITEM_CODE IN (SELECT ITEM_CODE FROM ID_ITEM WHERE SUPPLIER_CODE = 'IP')
 GROUP BY w.ITEM_CODE, w.ORGANIZATION_ID
/
CREATE UNIQUE INDEX UX_IM_WS_RECEIPT_AOI_RT ON IM_ITEM_WORKSTAGE_RECEIPT
  (CASE WHEN ENTER_BY = 'AOI_RT' THEN RECEIPT_DATE END,
   CASE WHEN ENTER_BY = 'AOI_RT' THEN ITEM_CODE END,
   CASE WHEN ENTER_BY = 'AOI_RT' THEN ORGANIZATION_ID END)
/
CREATE UNIQUE INDEX UX_IM_WS_ISSUE_AOI_RT ON IM_ITEM_WORKSTAGE_ISSUE
  (CASE WHEN ENTER_BY = 'AOI_RT' THEN ISSUE_DATE END,
   CASE WHEN ENTER_BY = 'AOI_RT' THEN ITEM_CODE END,
   CASE WHEN ENTER_BY = 'AOI_RT' THEN ORGANIZATION_ID END)
/
CREATE OR REPLACE TRIGGER TRG_IM_WS_RECEIPT_INFAC
  /* 인팩 전송용 공정재고: 공정입고(자재 출고 등) + . AOI 실시간 반제품 입고(AOI_RT)는 넣지 않는다. 2026-10-17 */
  AFTER INSERT OR UPDATE OF RECEIPT_QTY ON IM_ITEM_WORKSTAGE_RECEIPT
  FOR EACH ROW
  WHEN (NVL(NEW.ENTER_BY, '*') <> 'AOI_RT')
DECLARE
  v_qty NUMBER := NVL(:NEW.RECEIPT_QTY, 0) - NVL(:OLD.RECEIPT_QTY, 0);
  v_cnt NUMBER;
BEGIN
  IF v_qty = 0 THEN RETURN; END IF;
  SELECT COUNT(*) INTO v_cnt FROM ID_ITEM WHERE ITEM_CODE = :NEW.ITEM_CODE AND SUPPLIER_CODE = 'IP' AND ROWNUM = 1;
  IF v_cnt = 0 THEN RETURN; END IF;
  MERGE INTO IM_ITEM_WS_INV_INFAC t
  USING (SELECT :NEW.ITEM_CODE c, :NEW.ORGANIZATION_ID o FROM DUAL) s
     ON (t.ITEM_CODE = s.c AND t.ORGANIZATION_ID = s.o)
   WHEN MATCHED THEN UPDATE SET t.INVENTORY_QTY = NVL(t.INVENTORY_QTY, 0) + v_qty, t.LAST_MODIFY_DATE = SYSDATE, t.LAST_MODIFY_BY = 'WS RECEIPT'
   WHEN NOT MATCHED THEN INSERT (ITEM_CODE, ORGANIZATION_ID, INVENTORY_QTY, LAST_MODIFY_DATE, LAST_MODIFY_BY)
                         VALUES (s.c, s.o, v_qty, SYSDATE, 'WS RECEIPT');
END;
/
CREATE OR REPLACE TRIGGER TRG_IM_WS_ISSUE_INFAC
  /* 인팩 전송용 공정재고: 공정실사 조정 출고(LAST_MODIFY_BY = 'INV ADJUST')만 − .
     생산투입(제품 입고 × BOM 말단)은 P_WIP_ISSUE_CREATE 가 이 테이블에 직접 반영한다. 2026-10-17 */
  AFTER INSERT OR UPDATE OF ISSUE_QTY ON IM_ITEM_WORKSTAGE_ISSUE
  FOR EACH ROW
  WHEN (NEW.LAST_MODIFY_BY = 'INV ADJUST')
DECLARE
  v_qty NUMBER := NVL(:NEW.ISSUE_QTY, 0) - NVL(:OLD.ISSUE_QTY, 0);
  v_cnt NUMBER;
BEGIN
  IF v_qty = 0 THEN RETURN; END IF;
  SELECT COUNT(*) INTO v_cnt FROM ID_ITEM WHERE ITEM_CODE = :NEW.ITEM_CODE AND SUPPLIER_CODE = 'IP' AND ROWNUM = 1;
  IF v_cnt = 0 THEN RETURN; END IF;
  MERGE INTO IM_ITEM_WS_INV_INFAC t
  USING (SELECT :NEW.ITEM_CODE c, :NEW.ORGANIZATION_ID o FROM DUAL) s
     ON (t.ITEM_CODE = s.c AND t.ORGANIZATION_ID = s.o)
   WHEN MATCHED THEN UPDATE SET t.INVENTORY_QTY = NVL(t.INVENTORY_QTY, 0) - v_qty, t.LAST_MODIFY_DATE = SYSDATE, t.LAST_MODIFY_BY = 'INV ADJUST'
   WHEN NOT MATCHED THEN INSERT (ITEM_CODE, ORGANIZATION_ID, INVENTORY_QTY, LAST_MODIFY_DATE, LAST_MODIFY_BY)
                         VALUES (s.c, s.o, -v_qty, SYSDATE, 'INV ADJUST');
END;
/
