DECLARE
  -- 2026-11-05 완제품 실적(IP_PRODUCT_RESULT)에 타임구간·작업일 컬럼 추가 (멱등)
  --   TIME_ZONE   타임구간 A~J (작업시간 관리 ICOM_WORKTIME_RANGES 의 WORK_TYPE)
  --   ACTUAL_DATE 작업일 (F_GET_WORK_ACTUAL_DATE, 08:30 시작) — 기존 행은 PRODUCT_DATE(저장 때 같은 식으로 채운 값)로 채운다
  --   SHIFT_CODE  는 이미 있다 (근무조 A/B). 기존 행의 TIME_ZONE·SHIFT_CODE 는 알 수 없어 비워 둔다.
  v_table NUMBER;
  v_cnt   NUMBER;

  PROCEDURE add_col(p_col VARCHAR2, p_ddl VARCHAR2) IS
  BEGIN
    SELECT COUNT(*) INTO v_cnt FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'IP_PRODUCT_RESULT' AND COLUMN_NAME = p_col;
    IF v_cnt = 0 THEN
      EXECUTE IMMEDIATE 'ALTER TABLE IP_PRODUCT_RESULT ADD (' || p_ddl || ')';
    END IF;
  END;
BEGIN
  SELECT COUNT(*) INTO v_table FROM USER_TABLES WHERE TABLE_NAME = 'IP_PRODUCT_RESULT';
  IF v_table = 0 THEN
    RAISE_APPLICATION_ERROR(-20001, 'IP_PRODUCT_RESULT 테이블이 없습니다. 완제품 실적 마이그레이션을 먼저 적용하세요.');
  END IF;

  add_col('TIME_ZONE', 'TIME_ZONE VARCHAR2(2)');
  add_col('ACTUAL_DATE', 'ACTUAL_DATE DATE');

  EXECUTE IMMEDIATE q'[COMMENT ON COLUMN IP_PRODUCT_RESULT.TIME_ZONE IS '타임구간 A~J (작업시간 관리 WORKTIME 구간)']';
  EXECUTE IMMEDIATE q'[COMMENT ON COLUMN IP_PRODUCT_RESULT.ACTUAL_DATE IS '작업일 (08:30 기준 업무일)']';

  EXECUTE IMMEDIATE 'UPDATE IP_PRODUCT_RESULT SET ACTUAL_DATE = TRUNC(PRODUCT_DATE) WHERE ACTUAL_DATE IS NULL';
  COMMIT;
END;
