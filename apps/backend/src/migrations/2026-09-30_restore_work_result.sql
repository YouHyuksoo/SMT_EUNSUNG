-- 설비별 작업 실적 원장 복원 (IP_PRODUCT_WORK_RESULT)
-- 2026-09-02에 IP_PRODUCT_SENSOR_ACTUAL로 전환하며 DROP했던 테이블을 되살린다.
-- 센서 누적은 P_INTERLOCK_SENSOR_ACTUAL_NEO가 담당하고, 건별 실적 이력은 이 테이블이 맡는다.
-- 계획: docs/plans/2026-09-30-work-result-restore-sensor-proc.md
--
-- ES_JSIDC에는 휴지통 사본(BIN$koAumyN1TTaJP/V4de49KQ==$0)이 남아 있다고 기록돼 있다.
-- 생존해 있으면 아래 CREATE 대신 FLASHBACK으로 되살리고 컬럼 2개만 추가한다.
--   FLASHBACK TABLE IP_PRODUCT_WORK_RESULT TO BEFORE DROP;
--   ALTER TABLE IP_PRODUCT_WORK_RESULT ADD (SENSOR_APPLY_YN VARCHAR2(1) DEFAULT 'N', SENSOR_APPLY_MSG VARCHAR2(1000));

CREATE TABLE IP_PRODUCT_WORK_RESULT (
  RUN_NO            VARCHAR2(30)  NOT NULL,
  SEQ_NO            VARCHAR2(2)   NOT NULL,
  ORGANIZATION_ID   NUMBER        NOT NULL,
  MACHINE_CODE      VARCHAR2(30),
  WORKSTAGE_CODE    VARCHAR2(10),
  RESULT_QTY        NUMBER        DEFAULT 0,
  WORK_TIME         NUMBER        DEFAULT 0,
  WORKER_COUNT      NUMBER        DEFAULT 0,
  WORKER_NAME       VARCHAR2(100),
  RESULT_STATUS     VARCHAR2(10)  DEFAULT 'WIP',
  SENSOR_APPLY_YN   VARCHAR2(1)   DEFAULT 'N',
  SENSOR_APPLY_MSG  VARCHAR2(1000),
  ENTER_BY          VARCHAR2(20),
  ENTER_DATE        DATE,
  LAST_MODIFY_BY    VARCHAR2(20),
  LAST_MODIFY_DATE  DATE,
  CONSTRAINT PK_IP_PRODUCT_WORK_RESULT PRIMARY KEY (RUN_NO, SEQ_NO, ORGANIZATION_ID)
)
/

COMMENT ON TABLE IP_PRODUCT_WORK_RESULT IS '설비별 작업 실적 헤더 (작업지시별 복수 실적)'
/
COMMENT ON COLUMN IP_PRODUCT_WORK_RESULT.SEQ_NO IS '실적 일련번호 (2자리 01~99)'
/
COMMENT ON COLUMN IP_PRODUCT_WORK_RESULT.RESULT_STATUS IS '처리구분: WIP=진행, DONE=완료(수정불가)'
/
COMMENT ON COLUMN IP_PRODUCT_WORK_RESULT.MACHINE_CODE IS '설비코드 (IMCN_MACHINE.MACHINE_CODE)'
/
COMMENT ON COLUMN IP_PRODUCT_WORK_RESULT.WORKSTAGE_CODE IS '공정코드 (IP_PRODUCT_WORKSTAGE.WORKSTAGE_CODE)'
/
COMMENT ON COLUMN IP_PRODUCT_WORK_RESULT.SENSOR_APPLY_YN IS '센서실적 반영여부: Y=P_INTERLOCK_SENSOR_ACTUAL_NEO 반영완료, N=미반영(진행중이거나 호출실패)'
/
COMMENT ON COLUMN IP_PRODUCT_WORK_RESULT.SENSOR_APPLY_MSG IS 'P_INTERLOCK_SENSOR_ACTUAL_NEO의 마지막 P_OUT 원문 (OK가 아니면 실패사유)'
/
