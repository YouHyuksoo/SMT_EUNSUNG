-- 2026-10-17 AOI 실적 → 조립실적(IP_ASSEMBLY_RESULT) 적재 — 1단계
--
-- 설계: docs/specs/2026-10-17-wip-semi-product-from-aoi-design.md (4장 1·2)
--   AOI 양품(PID·면) 하나를 한 번만 세어 런·면·생산 품목별로 조립실적에 넣는다.
--   공정입고·공정출고(재고 움직임)는 2단계에서 WORKSTAGE_ISSUE_YN = 'N' 인 조립실적을 읽어 만든다.
--   이 단계는 재고를 움직이지 않는다.
-- 구성
--   IP_ASSEMBLY_RESULT_AOI_PID  PID·면 처리 기록 (중복 방지 + 조립실적 행 연결)
--   SEQ_ASSEMBLY_RESULT_SEQ     조립실적 PRODUCT_SEQUENCE
--   ISYS_CONFIG ASSY_RESULT_AOI_FROM  이 검사시각부터 읽는다 (AOI INSPECT_DATE 문자열 형식)
--   P_ASSY_RESULT_FROM_AOI      적재 프로시저 (oracle_db_scripts/P_ASSY_RESULT_FROM_AOI.sql)
--   DBMS_JOB 2개: 5분마다 최근 2시간, 매일 07:40 최근 2일 (늦게 붙는 AOI 리뷰를 받는다)
-- 되돌리기: 맨 아래.
-- =====================================================================
CREATE TABLE IP_ASSEMBLY_RESULT_AOI_PID (
  ORGANIZATION_ID   NUMBER        NOT NULL,
  PID               VARCHAR2(100) NOT NULL,
  PCB_SIDE          VARCHAR2(1)   NOT NULL,
  RUN_NO            VARCHAR2(50),
  LINE_CODE         VARCHAR2(20),
  ITEM_CODE         VARCHAR2(30),
  INSPECT_DATE      VARCHAR2(30),
  BATCH_ID          NUMBER,
  PRODUCT_DATE      DATE,
  PRODUCT_SEQUENCE  NUMBER,
  ENTER_DATE        DATE DEFAULT SYSDATE,
  CONSTRAINT PK_IP_ASSY_RESULT_AOI_PID PRIMARY KEY (PID, PCB_SIDE, ORGANIZATION_ID)
)
/
CREATE INDEX IX_IP_ASSY_RESULT_AOI_PID_1 ON IP_ASSEMBLY_RESULT_AOI_PID (BATCH_ID)
/
CREATE INDEX IX_IP_ASSY_RESULT_AOI_PID_2 ON IP_ASSEMBLY_RESULT_AOI_PID (INSPECT_DATE)
/
CREATE INDEX IX_IP_ASSY_RESULT_AOI_PID_3 ON IP_ASSEMBLY_RESULT_AOI_PID (PRODUCT_DATE, PRODUCT_SEQUENCE)
/
BEGIN
  EXECUTE IMMEDIATE q'[COMMENT ON TABLE IP_ASSEMBLY_RESULT_AOI_PID IS 'AOI 양품 PID·면 처리 기록 — 조립실적 중복 방지 (P_ASSY_RESULT_FROM_AOI)']';
  EXECUTE IMMEDIATE q'[COMMENT ON COLUMN IP_ASSEMBLY_RESULT_AOI_PID.PCB_SIDE IS '면 T/B (런카드 PCB_ITEM)']';
  EXECUTE IMMEDIATE q'[COMMENT ON COLUMN IP_ASSEMBLY_RESULT_AOI_PID.ITEM_CODE IS '이 면 AOI 가 만든 품목 (모델 마스터 TOP_ITEM_CODE/BOTTOM_ITEM_CODE)']';
  EXECUTE IMMEDIATE q'[COMMENT ON COLUMN IP_ASSEMBLY_RESULT_AOI_PID.INSPECT_DATE IS '양품 판정 AOI 검사시각 (원본 문자열)']';
END;
/
CREATE SEQUENCE SEQ_ASSEMBLY_RESULT_SEQ START WITH 1 INCREMENT BY 1 NOCACHE
/
INSERT INTO ISYS_CONFIG (CONFIG_NAME, ORGANIZATION_ID, CONFIG_DESCRIPTION, CONFIG_VALUE, CONFIG_VALUE_DESCRIPTION, ENTER_DATE, ENTER_BY, LAST_MODIFY_DATE, LAST_MODIFY_BY, USE_YN)
SELECT 'ASSY_RESULT_AOI_FROM', 1, 'AOI 실적 조립실적 적재 시작 검사시각', '2026/10/17 00:00:00',
       'YYYY/MM/DD HH24:MI:SS — 이 시각 이전 AOI 는 조립실적으로 넣지 않는다', SYSDATE, 'ADMIN', SYSDATE, 'ADMIN', 'Y'
  FROM DUAL
 WHERE NOT EXISTS (SELECT 1 FROM ISYS_CONFIG WHERE CONFIG_NAME = 'ASSY_RESULT_AOI_FROM' AND ORGANIZATION_ID = 1)
/
COMMIT
