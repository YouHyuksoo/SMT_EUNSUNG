DECLARE
  v_count NUMBER;
  v_rows NUMBER;
BEGIN
  -- 1) 라우팅 그룹은 품목을 물지 않는다. 품목이 ID_ITEM.ROUTING_CODE 로 그룹을 문다.
  --    값이 남아 있으면 이관(docs/sql/2026-11-05-routing-by-code-data-move.sql)이 안 끝난 것이므로 멈춘다.
  SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS
   WHERE TABLE_NAME = 'IP_ROUTING_GROUPS' AND COLUMN_NAME = 'ITEM_CODE';
  IF v_count > 0 THEN
    EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM IP_ROUTING_GROUPS WHERE ITEM_CODE IS NOT NULL' INTO v_rows;
    IF v_rows > 0 THEN
      RAISE_APPLICATION_ERROR(-20010, 'IP_ROUTING_GROUPS.ITEM_CODE 값이 남아 있습니다. 데이터 이관을 먼저 실행하세요.');
    END IF;
    SELECT COUNT(*) INTO v_count FROM USER_CONSTRAINTS WHERE CONSTRAINT_NAME = 'FK_IP_RG_ITEM';
    IF v_count > 0 THEN
      EXECUTE IMMEDIATE 'ALTER TABLE IP_ROUTING_GROUPS DROP CONSTRAINT FK_IP_RG_ITEM';
    END IF;
    SELECT COUNT(*) INTO v_count FROM USER_INDEXES WHERE INDEX_NAME = 'UK_IP_RG_ACTIVE_ITEM';
    IF v_count > 0 THEN
      EXECUTE IMMEDIATE 'DROP INDEX UK_IP_RG_ACTIVE_ITEM';
    END IF;
    EXECUTE IMMEDIATE 'ALTER TABLE IP_ROUTING_GROUPS DROP COLUMN ITEM_CODE';
  END IF;

  -- 2) 투입자재는 (라우팅, 공정, 품목, 하위자재)로 둔다. 같은 라우팅을 쓰는 품목마다 BOM 이 달라서다.
  --    옛 구조(ITEM_CODE 없음)는 0건일 때만 다시 만든다.
  SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'IP_ROUTING_MATERIALS';
  IF v_count > 0 THEN
    SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'IP_ROUTING_MATERIALS' AND COLUMN_NAME = 'ITEM_CODE';
    IF v_count = 0 THEN
      EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM IP_ROUTING_MATERIALS' INTO v_rows;
      IF v_rows > 0 THEN
        RAISE_APPLICATION_ERROR(-20011, 'IP_ROUTING_MATERIALS 에 데이터가 있어 자동으로 다시 만들 수 없습니다.');
      END IF;
      EXECUTE IMMEDIATE 'DROP TABLE IP_ROUTING_MATERIALS';
    END IF;
  END IF;

  SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'IP_ROUTING_MATERIALS';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE q'~
      CREATE TABLE IP_ROUTING_MATERIALS (
        ORGANIZATION_ID NUMBER NOT NULL,
        ROUTING_CODE VARCHAR2(50) NOT NULL,
        PROCESS_SEQ NUMBER(10) NOT NULL,
        ITEM_CODE VARCHAR2(20) NOT NULL,
        CHILD_ITEM_CODE VARCHAR2(20) NOT NULL,
        ALLOC_QTY NUMBER(18,6) NOT NULL,
        ISSUE_METHOD VARCHAR2(20) DEFAULT 'BACKFLUSH' NOT NULL,
        CREATED_BY VARCHAR2(50),
        CREATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
        UPDATED_BY VARCHAR2(50),
        UPDATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
        CONSTRAINT PK_IP_ROUTING_MATERIALS PRIMARY KEY (ORGANIZATION_ID, ROUTING_CODE, PROCESS_SEQ, ITEM_CODE, CHILD_ITEM_CODE),
        CONSTRAINT FK_IP_RM_PROCESS FOREIGN KEY (ORGANIZATION_ID, ROUTING_CODE, PROCESS_SEQ)
          REFERENCES IP_ROUTING_PROCESSES (ORGANIZATION_ID, ROUTING_CODE, PROCESS_SEQ)
          DEFERRABLE INITIALLY IMMEDIATE,
        CONSTRAINT FK_IP_RM_PARENT FOREIGN KEY (ITEM_CODE, ORGANIZATION_ID, ROUTING_CODE)
          REFERENCES ID_ITEM (ITEM_CODE, ORGANIZATION_ID, ROUTING_CODE),
        CONSTRAINT FK_IP_RM_ITEM FOREIGN KEY (CHILD_ITEM_CODE, ORGANIZATION_ID)
          REFERENCES ID_ITEM (ITEM_CODE, ORGANIZATION_ID),
        CONSTRAINT UK_IP_RM_CHILD UNIQUE (ORGANIZATION_ID, ROUTING_CODE, ITEM_CODE, CHILD_ITEM_CODE),
        CONSTRAINT CK_IP_RM_QTY CHECK (ALLOC_QTY > 0),
        CONSTRAINT CK_IP_RM_METHOD CHECK (ISSUE_METHOD IN ('BACKFLUSH', 'PRE_ISSUE'))
      )~';
  END IF;

  -- 3) 옛 라우팅 테이블 삭제. 0건이고, 살아 있는 호출처가 없음을 확인했다
  --    (PKG_PLANNING 본문은 2026-08-11부터 INVALID, F_GET_WORKSTAGE_CODE_4_LINE 호출은 주석뿐).
  --    복구용 DDL: docs/sql/2026-11-05-ip-product-routing-legacy-ddl.sql
  SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'IP_PRODUCT_ROUTING';
  IF v_count > 0 THEN
    EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM IP_PRODUCT_ROUTING' INTO v_rows;
    IF v_rows > 0 THEN
      RAISE_APPLICATION_ERROR(-20012, 'IP_PRODUCT_ROUTING 에 데이터가 있어 삭제하지 않습니다.');
    END IF;
    EXECUTE IMMEDIATE 'DROP TABLE IP_PRODUCT_ROUTING';
  END IF;
  SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'IP_PRODUCT_ROUTING_MASTER';
  IF v_count > 0 THEN
    EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM IP_PRODUCT_ROUTING_MASTER' INTO v_rows;
    IF v_rows > 0 THEN
      RAISE_APPLICATION_ERROR(-20013, 'IP_PRODUCT_ROUTING_MASTER 에 데이터가 있어 삭제하지 않습니다.');
    END IF;
    EXECUTE IMMEDIATE 'DROP TABLE IP_PRODUCT_ROUTING_MASTER';
  END IF;
END;
