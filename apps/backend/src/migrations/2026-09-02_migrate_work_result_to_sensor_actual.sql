DECLARE
  -- IP_PRODUCT_WORK_RESULT -> IP_PRODUCT_SENSOR_ACTUAL 데이터 이관 (멱등).
  -- RECEIPT_DATE 는 원본 등록일자(ENTER_DATE)를 그대로 쓴다 — 이관으로 등록시각이 바뀌면 안 된다.
  -- RECEIPT_SEQUENCE 는 레거시 전역 시퀀스로 새로 채번한다(원본 SEQ_NO는 작업지시별 01~99라 PK로 못 쓴다).
  -- 처리구분 RESULT_STATUS(WIP/DONE) -> IS_LAST_YN(N/Y).
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME = 'IP_PRODUCT_WORK_RESULT';
  IF n = 0 THEN RETURN; END IF;

  INSERT INTO IP_PRODUCT_SENSOR_ACTUAL (
    RECEIPT_DATE, RECEIPT_SEQUENCE, ORGANIZATION_ID, RUN_NO,
    MACHINE_CODE, WORKSTAGE_CODE, PRODUCT_ACTUAL_QTY,
    WORK_TIME, WORKER_COUNT, WORKER_NAME, IS_LAST_YN,
    ENTER_BY, ENTER_DATE, LAST_MODIFY_BY, LAST_MODIFY_DATE
  )
  SELECT w.ENTER_DATE, SEQ_PRODUCT_SENSOR.NEXTVAL, w.ORGANIZATION_ID, w.RUN_NO,
         w.MACHINE_CODE, w.WORKSTAGE_CODE, w.RESULT_QTY,
         w.WORK_TIME, w.WORKER_COUNT, w.WORKER_NAME,
         CASE WHEN w.RESULT_STATUS = 'DONE' THEN 'Y' ELSE 'N' END,
         w.ENTER_BY, w.ENTER_DATE, w.LAST_MODIFY_BY, w.LAST_MODIFY_DATE
    FROM IP_PRODUCT_WORK_RESULT w
   WHERE NOT EXISTS (
           SELECT 1 FROM IP_PRODUCT_SENSOR_ACTUAL s
            WHERE s.RUN_NO = w.RUN_NO
              AND s.ORGANIZATION_ID = w.ORGANIZATION_ID
              AND s.RECEIPT_DATE = w.ENTER_DATE
         );
  COMMIT;
END;
/
