-- =====================================================================
-- 2026-10-14 설비별 검사실적 원장 IQ_EQUIP_INSPECT_RESULT — ESDBext 적용
--
-- 설비별 검사실적관리(/oee/equip-inspect-result)가 쓴다. 생산실적(IP_PRODUCT_WORK_RESULT)과 별도다.
-- 검사공정(공정유형 Q: ICT·성능검사 등) 설비에서 작업지시(IP_PRODUCT_RUN_CARD) 단위로
-- 판정(합격/불합격)·수량·불량원인을 한 건씩 쌓는다. 작업지시·센서 누적은 건드리지 않는다.
--
-- 판정     : ISYS_BASECODE 'INSPECT RESULT' 의 P=합격, R=불합격 만 쓴다.
-- 불량원인 : ISYS_CODE_MASTER 'WQC BAD REASON CODE' (설비별 작업 실적관리 불량등록과 같은 코드).
--            불합격이면 필수, 합격이면 비운다 (CHECK 로 강제).
-- 취소     : 행은 남기고 RESULT_STATUS='CANCEL'. 오늘 업무일(F_GET_WORK_ACTUAL_DATE) 건만 화면에서 취소한다.
-- =====================================================================

CREATE TABLE IQ_EQUIP_INSPECT_RESULT (
  RUN_NO           VARCHAR2(30)  NOT NULL,
  SEQ_NO           NUMBER(6)     NOT NULL,
  ORGANIZATION_ID  NUMBER        NOT NULL,
  MACHINE_CODE     VARCHAR2(30)  NOT NULL,
  WORKSTAGE_CODE   VARCHAR2(10)  NOT NULL,
  INSPECT_RESULT   VARCHAR2(1)   NOT NULL,
  INSPECT_QTY      NUMBER        NOT NULL,
  BAD_REASON_CODE  VARCHAR2(20),
  INSPECTOR_NAME   VARCHAR2(100),
  RESULT_STATUS    VARCHAR2(10)  DEFAULT 'DONE' NOT NULL,
  ENTER_BY         VARCHAR2(20),
  ENTER_DATE       DATE          DEFAULT SYSDATE,
  LAST_MODIFY_BY   VARCHAR2(20),
  LAST_MODIFY_DATE DATE,
  CONSTRAINT PK_IQ_EQUIP_INSPECT_RESULT PRIMARY KEY (RUN_NO, SEQ_NO, ORGANIZATION_ID),
  CONSTRAINT CK_IQ_EQUIP_INSP_RESULT CHECK (INSPECT_RESULT IN ('P', 'R')),
  CONSTRAINT CK_IQ_EQUIP_INSP_STATUS CHECK (RESULT_STATUS IN ('DONE', 'CANCEL')),
  CONSTRAINT CK_IQ_EQUIP_INSP_QTY CHECK (INSPECT_QTY > 0),
  CONSTRAINT CK_IQ_EQUIP_INSP_BAD CHECK (
    (INSPECT_RESULT = 'P' AND BAD_REASON_CODE IS NULL) OR
    (INSPECT_RESULT = 'R' AND BAD_REASON_CODE IS NOT NULL))
)
/
CREATE INDEX IX_IQ_EQUIP_INSPECT_RESULT1 ON IQ_EQUIP_INSPECT_RESULT (MACHINE_CODE, ENTER_DATE)
/
COMMENT ON TABLE IQ_EQUIP_INSPECT_RESULT IS '설비별 검사실적 (작업지시별 판정 건)'
/
COMMENT ON COLUMN IQ_EQUIP_INSPECT_RESULT.RUN_NO IS '작업지시(롯트카드) 번호 (IP_PRODUCT_RUN_CARD.RUN_NO)'
/
COMMENT ON COLUMN IQ_EQUIP_INSPECT_RESULT.SEQ_NO IS '검사실적 일련번호 (작업지시별 1부터)'
/
COMMENT ON COLUMN IQ_EQUIP_INSPECT_RESULT.ORGANIZATION_ID IS '조직ID'
/
COMMENT ON COLUMN IQ_EQUIP_INSPECT_RESULT.MACHINE_CODE IS '검사설비코드 (IMCN_MACHINE.MACHINE_CODE)'
/
COMMENT ON COLUMN IQ_EQUIP_INSPECT_RESULT.WORKSTAGE_CODE IS '검사공정코드 (IP_PRODUCT_WORKSTAGE, 공정유형 Q)'
/
COMMENT ON COLUMN IQ_EQUIP_INSPECT_RESULT.INSPECT_RESULT IS '판정: P=합격, R=불합격 (ISYS_BASECODE INSPECT RESULT)'
/
COMMENT ON COLUMN IQ_EQUIP_INSPECT_RESULT.INSPECT_QTY IS '검사수량'
/
COMMENT ON COLUMN IQ_EQUIP_INSPECT_RESULT.BAD_REASON_CODE IS '불량원인 (ISYS_CODE_MASTER WQC BAD REASON CODE). 불합격이면 필수, 합격이면 NULL'
/
COMMENT ON COLUMN IQ_EQUIP_INSPECT_RESULT.INSPECTOR_NAME IS '검사자명'
/
COMMENT ON COLUMN IQ_EQUIP_INSPECT_RESULT.RESULT_STATUS IS '처리구분: DONE=확정, CANCEL=취소'
/
COMMENT ON COLUMN IQ_EQUIP_INSPECT_RESULT.ENTER_BY IS '등록자'
/
COMMENT ON COLUMN IQ_EQUIP_INSPECT_RESULT.ENTER_DATE IS '등록일자'
/
COMMENT ON COLUMN IQ_EQUIP_INSPECT_RESULT.LAST_MODIFY_BY IS '최종수정자'
/
COMMENT ON COLUMN IQ_EQUIP_INSPECT_RESULT.LAST_MODIFY_DATE IS '최종수정일자'
/

