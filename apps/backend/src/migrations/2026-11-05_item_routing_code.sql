DECLARE
  v_count NUMBER;
  v_nullable VARCHAR2(1);
BEGIN
  -- 1) 품목이 라우팅 코드를 물도록 ID_ITEM.ROUTING_CODE 를 추가한다.
  --    ROUTE_NO 는 쓰지 않는다: UPDATE OF ROUTE_NO 트리거(ID_ITEM_UPD_MANUAL)가 재고 행을 지운다.
  --    ROUTING_CODE 는 어떤 ID_ITEM 트리거의 UPDATE OF 대상도 아니다.
  SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS
   WHERE TABLE_NAME = 'ID_ITEM' AND COLUMN_NAME = 'ROUTING_CODE';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE ID_ITEM ADD (ROUTING_CODE VARCHAR2(50))';
  END IF;

  -- 투입자재가 (품목, 라우팅) 쌍을 가리킬 수 있도록 하는 참조 대상. 품목이 다른 라우팅으로 옮겨가면
  -- 투입자재가 남아 있는 한 DB 가 막는다.
  SELECT COUNT(*) INTO v_count FROM USER_CONSTRAINTS WHERE CONSTRAINT_NAME = 'UK_ID_ITEM_ROUTING';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE ID_ITEM ADD CONSTRAINT UK_ID_ITEM_ROUTING UNIQUE (ITEM_CODE, ORGANIZATION_ID, ROUTING_CODE)';
  END IF;

  SELECT COUNT(*) INTO v_count FROM USER_CONSTRAINTS WHERE CONSTRAINT_NAME = 'FK_ID_ITEM_ROUTING';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE ID_ITEM ADD CONSTRAINT FK_ID_ITEM_ROUTING FOREIGN KEY (ORGANIZATION_ID, ROUTING_CODE) REFERENCES IP_ROUTING_GROUPS (ORGANIZATION_ID, ROUTING_CODE)';
  END IF;

  SELECT COUNT(*) INTO v_count FROM USER_INDEXES WHERE INDEX_NAME = 'IX_ID_ITEM_ROUTING';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'CREATE INDEX IX_ID_ITEM_ROUTING ON ID_ITEM (ORGANIZATION_ID, ROUTING_CODE)';
  END IF;

  -- 2) 라우팅 그룹이 더 이상 품목을 물지 않는다. 옛 구조(IP_ROUTING_GROUPS.ITEM_CODE)가 남아 있으면
  --    데이터 이관 전에 제약만 풀어 둔다. 컬럼 삭제는 2026-11-05_routing_groups_drop_item_code.sql 이 한다.
  SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS
   WHERE TABLE_NAME = 'IP_ROUTING_GROUPS' AND COLUMN_NAME = 'ITEM_CODE';
  IF v_count > 0 THEN
    SELECT COUNT(*) INTO v_count FROM USER_CONSTRAINTS WHERE CONSTRAINT_NAME = 'FK_IP_RG_ITEM';
    IF v_count > 0 THEN
      EXECUTE IMMEDIATE 'ALTER TABLE IP_ROUTING_GROUPS DROP CONSTRAINT FK_IP_RG_ITEM';
    END IF;
    SELECT COUNT(*) INTO v_count FROM USER_INDEXES WHERE INDEX_NAME = 'UK_IP_RG_ACTIVE_ITEM';
    IF v_count > 0 THEN
      EXECUTE IMMEDIATE 'DROP INDEX UK_IP_RG_ACTIVE_ITEM';
    END IF;
    SELECT NULLABLE INTO v_nullable FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'IP_ROUTING_GROUPS' AND COLUMN_NAME = 'ITEM_CODE';
    IF v_nullable = 'N' THEN
      EXECUTE IMMEDIATE 'ALTER TABLE IP_ROUTING_GROUPS MODIFY (ITEM_CODE NULL)';
    END IF;
  END IF;

  SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS
   WHERE TABLE_NAME = 'ID_ITEM' AND COLUMN_NAME = 'ROUTING_CODE'
     AND DATA_TYPE = 'VARCHAR2' AND DATA_LENGTH = 50 AND NULLABLE = 'Y';
  IF v_count <> 1 THEN
    RAISE_APPLICATION_ERROR(-20001, 'ID_ITEM.ROUTING_CODE definition mismatch');
  END IF;
END;
/
