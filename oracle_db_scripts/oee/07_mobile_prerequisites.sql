  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE OEE_DOWNTIME_EVENT ADD CONSTRAINT UQ_OEE_DTE_START_REQ UNIQUE (ORGANIZATION_ID, START_REQUEST_ID)';
  END IF;
END;
/

DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count
    FROM USER_CONSTRAINTS
   WHERE TABLE_NAME = 'OEE_DOWNTIME_EVENT'
     AND CONSTRAINT_NAME = 'UQ_OEE_DTE_END_REQ';
  IF v_count > 0 THEN
    -- A composite Oracle UNIQUE constraint indexes ORGANIZATION_ID even when
    -- END_REQUEST_ID is null, so it permits only one open row per organization.
    EXECUTE IMMEDIATE 'ALTER TABLE OEE_DOWNTIME_EVENT DROP CONSTRAINT UQ_OEE_DTE_END_REQ';
  END IF;
END;
/

DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count
    FROM USER_INDEXES
   WHERE INDEX_NAME = 'UX_OEE_DTE_END_REQ';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE UNIQUE INDEX UX_OEE_DTE_END_REQ
        ON OEE_DOWNTIME_EVENT (
          CASE WHEN END_REQUEST_ID IS NOT NULL THEN ORGANIZATION_ID END,
          CASE WHEN END_REQUEST_ID IS NOT NULL THEN END_REQUEST_ID END
        )
    ]';
  END IF;
END;
