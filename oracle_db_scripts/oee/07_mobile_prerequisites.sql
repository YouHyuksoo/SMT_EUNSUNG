DECLARE
  -- OEE MOBILE 비가동 이벤트 저장 테이블.
  -- oracle_connector.py가 PL/SQL로 인식하도록 DECLARE가 파일의 첫 토큰이어야 한다.
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count
    FROM USER_TABLES
   WHERE TABLE_NAME = 'OEE_DOWNTIME_EVENT';

  IF v_count = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE OEE_DOWNTIME_EVENT (
        EVENT_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY,
        ORGANIZATION_ID   NUMBER        NOT NULL,
        RESOURCE_TYPE     VARCHAR2(10)  NOT NULL,
        RESOURCE_CODE     VARCHAR2(50)  NOT NULL,
        PARENT_LINE_CODE  VARCHAR2(50)  NOT NULL,
        PROCESS_CODE      VARCHAR2(20)  NOT NULL,
        WORK_DATE         DATE          NOT NULL,
        WORK_SEGMENT      VARCHAR2(1)   NOT NULL,
        START_TIME        TIMESTAMP(6)  NOT NULL,
        END_TIME          TIMESTAMP(6),
        REASON_CODE       VARCHAR2(100) NOT NULL,
        MEMO              VARCHAR2(500),
        WORKER_ID         VARCHAR2(20)  NOT NULL,
        START_REQUEST_ID  VARCHAR2(64)  NOT NULL,
        END_REQUEST_ID    VARCHAR2(64),
        STARTED_BY        VARCHAR2(20)  NOT NULL,
        ENDED_BY          VARCHAR2(20),
        CREATED_DATE      TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
        UPDATED_DATE      TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
        CONSTRAINT PK_OEE_DTE PRIMARY KEY (EVENT_ID),
        CONSTRAINT UQ_OEE_DTE_START_REQ UNIQUE (ORGANIZATION_ID, START_REQUEST_ID),
        CONSTRAINT CK_OEE_DTE_RESOURCE CHECK (RESOURCE_TYPE IN ('LINE', 'CELL')),
        CONSTRAINT CK_OEE_DTE_PROCESS CHECK (PROCESS_CODE IN ('SMT', 'ASSY')),
        CONSTRAINT CK_OEE_DTE_WORK_SEGMENT CHECK (WORK_SEGMENT IN ('A', 'B', 'C', 'D', 'E', 'F', 'G', 'H', 'I', 'J'))
      )
    ]';
  END IF;
END;
/

DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count
    FROM USER_CONSTRAINTS
   WHERE TABLE_NAME = 'OEE_DOWNTIME_EVENT'
     AND CONSTRAINT_NAME = 'PK_OEE_DTE';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE OEE_DOWNTIME_EVENT ADD CONSTRAINT PK_OEE_DTE PRIMARY KEY (EVENT_ID)';
  END IF;
END;
/

