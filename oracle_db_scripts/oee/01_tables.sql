DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'OEE_RESOURCE';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE OEE_RESOURCE (
        RESOURCE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        ORGANIZATION_ID NUMBER NOT NULL,
        PROCESS_CODE VARCHAR2(20) NOT NULL,
        RESOURCE_TYPE VARCHAR2(20) NOT NULL,
        REF_CODE VARCHAR2(50),
        RESOURCE_NAME VARCHAR2(100) NOT NULL,
        IDEAL_CT NUMBER,
        USE_YN CHAR(1) DEFAULT 'Y' NOT NULL,
        SORT_ORDER NUMBER DEFAULT 0 NOT NULL
      )
    ]';
  END IF;
END;
