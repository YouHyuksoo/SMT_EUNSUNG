CREATE OR REPLACE NONEDITIONABLE VIEW V_OEE_PRODUCT_LINE AS
SELECT l.ORGANIZATION_ID,
       l.LINE_CODE,
       l.LINE_NAME,
       l.PROCESS_CODE,
       l.RESOURCE_TYPE,
       l.PARENT_LINE_CODE,
       l.ACTIVE_YN,
       l.MES_DISPLAY_YN,
       l.MES_DISPLAY_SEQUENCE AS SORT_ORDER
  FROM IP_PRODUCT_LINE l
 WHERE l.PROCESS_CODE IN ('SMT', 'ASSY')
   AND l.RESOURCE_TYPE IN ('LINE', 'CELL')
   AND l.LINE_CODE IS NOT NULL
   AND l.LINE_NAME IS NOT NULL
/
