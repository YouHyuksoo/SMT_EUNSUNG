BEGIN
  UPDATE OEE_DOWNTIME_EVENT
     SET WORK_SEGMENT = 'DAY'
   WHERE WORK_SEGMENT IN ('A', 'B', 'C', 'D', 'E');

  UPDATE OEE_DOWNTIME_EVENT
     SET WORK_SEGMENT = 'NIGHT'
   WHERE WORK_SEGMENT IN ('F', 'G', 'H', 'I', 'J');
END;
