DECLARE
  v_table_count NUMBER;
  v_invalid_count NUMBER;
BEGIN
  SELECT COUNT(*)
    INTO v_table_count
    FROM USER_TABLES
   WHERE TABLE_NAME IN (
     'OEE_OPERATION_LOG',
     'OEE_PLAN_TIME',
     'OEE_DAILY_SUMMARY',
     'OEE_PRODUCTION_RESULT',
     'OEE_DOWNTIME_EVENT'
   );

  IF v_table_count <> 5 THEN
    RAISE_APPLICATION_ERROR(-20031, 'OEE shift contract preflight requires all five OEE tables.');
  END IF;

  EXECUTE IMMEDIATE q'[SELECT COUNT(*) FROM OEE_OPERATION_LOG WHERE SHIFT IS NULL OR SHIFT NOT IN ('DAY', 'NIGHT')]'
    INTO v_invalid_count;
  IF v_invalid_count > 0 THEN
    RAISE_APPLICATION_ERROR(-20032, 'OEE_OPERATION_LOG contains a non-DAY/NIGHT SHIFT.');
  END IF;

  EXECUTE IMMEDIATE q'[SELECT COUNT(*) FROM OEE_PLAN_TIME WHERE SHIFT IS NULL OR SHIFT NOT IN ('DAY', 'NIGHT')]'
    INTO v_invalid_count;
  IF v_invalid_count > 0 THEN
    RAISE_APPLICATION_ERROR(-20033, 'OEE_PLAN_TIME contains a non-DAY/NIGHT SHIFT.');
  END IF;

  EXECUTE IMMEDIATE q'[SELECT COUNT(*) FROM OEE_DAILY_SUMMARY WHERE SHIFT IS NULL OR SHIFT NOT IN ('DAY', 'NIGHT')]'
    INTO v_invalid_count;
  IF v_invalid_count > 0 THEN
    RAISE_APPLICATION_ERROR(-20034, 'OEE_DAILY_SUMMARY contains a non-DAY/NIGHT SHIFT.');
  END IF;

  EXECUTE IMMEDIATE q'[SELECT COUNT(*) FROM OEE_PRODUCTION_RESULT WHERE SHIFT IS NULL OR SHIFT NOT IN ('DAY', 'NIGHT')]'
    INTO v_invalid_count;
  IF v_invalid_count > 0 THEN
    RAISE_APPLICATION_ERROR(-20035, 'OEE_PRODUCTION_RESULT contains a non-DAY/NIGHT SHIFT.');
  END IF;

  EXECUTE IMMEDIATE q'[SELECT COUNT(*) FROM OEE_DOWNTIME_EVENT WHERE WORK_SEGMENT IS NULL OR WORK_SEGMENT NOT IN ('A', 'B', 'C', 'D', 'E', 'F', 'G', 'H', 'I', 'J', 'DAY', 'NIGHT')]'
    INTO v_invalid_count;
  IF v_invalid_count > 0 THEN
    RAISE_APPLICATION_ERROR(-20036, 'OEE_DOWNTIME_EVENT contains an unsupported WORK_SEGMENT.');
  END IF;
END;
/

DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*)
    INTO v_count
    FROM USER_CONSTRAINTS
   WHERE TABLE_NAME = 'OEE_DOWNTIME_EVENT'
     AND CONSTRAINT_NAME = 'CK_OEE_DTE_WORK_SEGMENT';
  IF v_count > 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE OEE_DOWNTIME_EVENT DROP CONSTRAINT CK_OEE_DTE_WORK_SEGMENT';
  END IF;
END;
