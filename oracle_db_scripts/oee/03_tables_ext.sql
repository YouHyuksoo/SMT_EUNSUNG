DECLARE
  v_count NUMBER;
BEGIN
  FOR c IN (
    SELECT 'PLAN_QTY' column_name, 'NUMBER DEFAULT 0' definition FROM DUAL UNION ALL
    SELECT 'PLAN_ACHIEVE', 'NUMBER DEFAULT 0' FROM DUAL UNION ALL
    SELECT 'UPH', 'NUMBER DEFAULT 0' FROM DUAL UNION ALL
    SELECT 'PICKUP_RATE', 'NUMBER' FROM DUAL
  ) LOOP
    SELECT COUNT(*) INTO v_count
      FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'OEE_DAILY_SUMMARY' AND COLUMN_NAME = c.column_name;
    IF v_count = 0 THEN
      EXECUTE IMMEDIATE 'ALTER TABLE OEE_DAILY_SUMMARY ADD (' || c.column_name || ' ' || c.definition || ')';
    END IF;
  END LOOP;
END;
