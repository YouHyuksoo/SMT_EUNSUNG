DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'OEE_PRODUCTION_RESULT';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE OEE_PRODUCTION_RESULT (
        RESULT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        ORGANIZATION_ID NUMBER NOT NULL,
        RESOURCE_ID NUMBER NOT NULL REFERENCES OEE_RESOURCE(RESOURCE_ID),
        PROCESS_CODE VARCHAR2(20) NOT NULL,
        WORK_DATE DATE NOT NULL,
        SHIFT VARCHAR2(10) NOT NULL,
        RUN_NO VARCHAR2(50),
        PLAN_QTY NUMBER DEFAULT 0 NOT NULL,
        OUTPUT_QTY NUMBER DEFAULT 0 NOT NULL,
        GOOD_QTY NUMBER DEFAULT 0 NOT NULL,
        DEFECT_QTY NUMBER DEFAULT 0 NOT NULL,
        PICKUP_RATE NUMBER,
        SOURCE VARCHAR2(10) DEFAULT 'MANUAL' NOT NULL,
        CREATED_BY VARCHAR2(50) NOT NULL,
        CREATED_DATE DATE DEFAULT SYSDATE NOT NULL,
        CONSTRAINT CK_OEE_PROD_SHIFT CHECK (SHIFT IN ('A','B','C','D','E','F','G','H','I','J')),
        CONSTRAINT CK_OEE_PROD_QTY CHECK (PLAN_QTY >= 0 AND OUTPUT_QTY >= 0 AND GOOD_QTY >= 0 AND DEFECT_QTY >= 0 AND GOOD_QTY + DEFECT_QTY = OUTPUT_QTY)
      )
    ]';
  END IF;
END;
