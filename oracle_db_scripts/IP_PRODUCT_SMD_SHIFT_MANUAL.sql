-- 반제품생산계획 주간·야간 수기실적 (2026-10-12, ESDB 적용)
-- 화면: 생산관리 > 반제품생산실적관리 > 계획별 주야 실적
-- 키: 반제품생산계획(IP_PRODUCT_SMD_PLAN) 키 PLAN_DATE + PLAN_SEQUENCE + ORGANIZATION_ID 에 근무조(SHIFT_SLOT)를 더한다.
-- SHIFT_SLOT: 'DAY' = 주간(08:30~20:30, 센서 시간구분 A~E), 'NIGHT' = 야간(20:30~다음날 08:30, F~J).
-- 행이 있으면 그 근무조는 수기 수량을 실적으로 쓰고, 행을 지우면 센서 자동 집계로 돌아간다.
-- 계획 테이블에 PK 제약이 없어(유일 인덱스만 있음) FK 는 걸지 않는다. (멱등)
DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME = 'IP_PRODUCT_SMD_SHIFT_MANUAL';
  IF n = 0 THEN
    EXECUTE IMMEDIATE '
      CREATE TABLE IP_PRODUCT_SMD_SHIFT_MANUAL (
        PLAN_DATE         DATE          NOT NULL,
        PLAN_SEQUENCE     NUMBER        NOT NULL,
        ORGANIZATION_ID   NUMBER        NOT NULL,
        SHIFT_SLOT        VARCHAR2(10)  NOT NULL,
        MANUAL_QTY        NUMBER        NOT NULL,
        ENTER_BY          VARCHAR2(30)  NOT NULL,
        ENTER_DATE        DATE          DEFAULT SYSDATE NOT NULL,
        LAST_MODIFY_BY    VARCHAR2(30),
        LAST_MODIFY_DATE  DATE,
        CONSTRAINT XPKIP_PRODUCT_SMD_SHIFT_MANUAL
          PRIMARY KEY (PLAN_DATE, PLAN_SEQUENCE, ORGANIZATION_ID, SHIFT_SLOT),
        CONSTRAINT CK_SMD_SHIFT_MANUAL_SLOT
          CHECK (SHIFT_SLOT IN (''DAY'', ''NIGHT'')),
        CONSTRAINT CK_SMD_SHIFT_MANUAL_QTY
          CHECK (MANUAL_QTY >= 0)
      )';
    EXECUTE IMMEDIATE 'COMMENT ON TABLE IP_PRODUCT_SMD_SHIFT_MANUAL IS ''반제품생산계획 주간/야간 수기실적. 행이 있으면 센서 자동집계 대신 이 수량을 실적으로 쓴다''';
    EXECUTE IMMEDIATE 'COMMENT ON COLUMN IP_PRODUCT_SMD_SHIFT_MANUAL.PLAN_DATE IS ''계획일자 (IP_PRODUCT_SMD_PLAN.PLAN_DATE)''';
    EXECUTE IMMEDIATE 'COMMENT ON COLUMN IP_PRODUCT_SMD_SHIFT_MANUAL.PLAN_SEQUENCE IS ''계획항번 (IP_PRODUCT_SMD_PLAN.PLAN_SEQUENCE)''';
    EXECUTE IMMEDIATE 'COMMENT ON COLUMN IP_PRODUCT_SMD_SHIFT_MANUAL.ORGANIZATION_ID IS ''조직ID''';
    EXECUTE IMMEDIATE 'COMMENT ON COLUMN IP_PRODUCT_SMD_SHIFT_MANUAL.SHIFT_SLOT IS ''근무조 DAY=주간(08:30~20:30, 시간구분 A~E) NIGHT=야간(20:30~다음날 08:30, F~J)''';
    EXECUTE IMMEDIATE 'COMMENT ON COLUMN IP_PRODUCT_SMD_SHIFT_MANUAL.MANUAL_QTY IS ''수기 실적수량''';
    EXECUTE IMMEDIATE 'COMMENT ON COLUMN IP_PRODUCT_SMD_SHIFT_MANUAL.ENTER_BY IS ''입력자''';
    EXECUTE IMMEDIATE 'COMMENT ON COLUMN IP_PRODUCT_SMD_SHIFT_MANUAL.ENTER_DATE IS ''입력일시''';
    EXECUTE IMMEDIATE 'COMMENT ON COLUMN IP_PRODUCT_SMD_SHIFT_MANUAL.LAST_MODIFY_BY IS ''최종수정자''';
    EXECUTE IMMEDIATE 'COMMENT ON COLUMN IP_PRODUCT_SMD_SHIFT_MANUAL.LAST_MODIFY_DATE IS ''최종수정일시''';
  END IF;
END;
/
