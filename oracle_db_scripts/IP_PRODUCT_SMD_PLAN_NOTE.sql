-- 반제품생산계획 현황판 특이사항·공지 (2026-10-12, ESDB 적용)
-- 화면: 생산관리 > 반제품생산계획 현황판 (/production/smd-plan-board)
-- 한 행 = 메모 한 줄. 날짜 + 라인 단위로 여러 줄을 NOTE_SEQ 순서로 보여준다.
-- LINE_CODE = '*' 이면 라인이 아니라 그 날짜 전체 공지(제목줄 옆)다.
-- 저장은 날짜 + 라인 단위로 통째로 바꾼다 (기존 줄 삭제 후 1..n 으로 다시 넣음).
-- 허용 범위: CREATE TABLE + PK + COMMENT. 시퀀스·인덱스·CHECK 는 만들지 않는다. (멱등)
DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME = 'IP_PRODUCT_SMD_PLAN_NOTE';
  IF n = 0 THEN
    EXECUTE IMMEDIATE '
      CREATE TABLE IP_PRODUCT_SMD_PLAN_NOTE (
        PLAN_DATE         DATE               NOT NULL,
        ORGANIZATION_ID   NUMBER             NOT NULL,
        LINE_CODE         VARCHAR2(10)       NOT NULL,
        NOTE_SEQ          NUMBER             NOT NULL,
        NOTE_TEXT         VARCHAR2(500 CHAR) NOT NULL,
        ENTER_BY          VARCHAR2(30)       NOT NULL,
        ENTER_DATE        DATE               DEFAULT SYSDATE NOT NULL,
        LAST_MODIFY_BY    VARCHAR2(30),
        LAST_MODIFY_DATE  DATE,
        CONSTRAINT XPKIP_PRODUCT_SMD_PLAN_NOTE
          PRIMARY KEY (PLAN_DATE, ORGANIZATION_ID, LINE_CODE, NOTE_SEQ)
      )';
    EXECUTE IMMEDIATE 'COMMENT ON TABLE IP_PRODUCT_SMD_PLAN_NOTE IS ''반제품생산계획 현황판 특이사항·공지. 날짜+라인 단위 메모 여러 줄, LINE_CODE=* 는 날짜 공지''';
    EXECUTE IMMEDIATE 'COMMENT ON COLUMN IP_PRODUCT_SMD_PLAN_NOTE.PLAN_DATE IS ''계획일자 (현황판 조회일)''';
    EXECUTE IMMEDIATE 'COMMENT ON COLUMN IP_PRODUCT_SMD_PLAN_NOTE.ORGANIZATION_ID IS ''조직ID''';
    EXECUTE IMMEDIATE 'COMMENT ON COLUMN IP_PRODUCT_SMD_PLAN_NOTE.LINE_CODE IS ''라인코드 (IP_PRODUCT_LINE.LINE_CODE). * = 날짜 전체 공지''';
    EXECUTE IMMEDIATE 'COMMENT ON COLUMN IP_PRODUCT_SMD_PLAN_NOTE.NOTE_SEQ IS ''표시 순서 (1부터)''';
    EXECUTE IMMEDIATE 'COMMENT ON COLUMN IP_PRODUCT_SMD_PLAN_NOTE.NOTE_TEXT IS ''메모 한 줄''';
    EXECUTE IMMEDIATE 'COMMENT ON COLUMN IP_PRODUCT_SMD_PLAN_NOTE.ENTER_BY IS ''입력자''';
    EXECUTE IMMEDIATE 'COMMENT ON COLUMN IP_PRODUCT_SMD_PLAN_NOTE.ENTER_DATE IS ''입력일시''';
    EXECUTE IMMEDIATE 'COMMENT ON COLUMN IP_PRODUCT_SMD_PLAN_NOTE.LAST_MODIFY_BY IS ''최종수정자''';
    EXECUTE IMMEDIATE 'COMMENT ON COLUMN IP_PRODUCT_SMD_PLAN_NOTE.LAST_MODIFY_DATE IS ''최종수정일시''';
  END IF;
END;
/
